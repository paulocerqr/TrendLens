    pipeline_run_id BIGINT REFERENCES pipeline_runs(id) ON DELETE SET NULL,
    workflow TEXT NOT NULL,
    node TEXT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    error_type TEXT NOT NULL,
    error_message TEXT NOT NULL,
    external_id TEXT,
    retry_count INTEGER NOT NULL DEFAULT 0,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT pipeline_errors_retry_count_check
        CHECK (retry_count >= 0),
    CONSTRAINT pipeline_errors_metadata_object_check
        CHECK (jsonb_typeof(metadata) = 'object')
);

CREATE TABLE IF NOT EXISTS video_collection_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_run_id BIGINT NOT NULL REFERENCES pipeline_runs(id) ON DELETE CASCADE,
    collection_query_id BIGINT NOT NULL REFERENCES collection_queries(id) ON DELETE RESTRICT,
    video_id BIGINT NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
    search_rank INTEGER NOT NULL,
    matched_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT video_collection_matches_identity_unique
        UNIQUE (pipeline_run_id, collection_query_id, video_id),
    CONSTRAINT video_collection_matches_search_rank_check
        CHECK (search_rank > 0)
);

CREATE OR REPLACE FUNCTION select_classification_candidates(
    p_limit INTEGER,
    p_description_max_chars INTEGER
)
RETURNS TABLE (
    video_id BIGINT,
    external_id TEXT,
    channel_name TEXT,
    title TEXT,
    description TEXT,
    published_at TIMESTAMPTZ,
    duration_seconds INTEGER,
    language VARCHAR(16),
    region CHAR(2),
    short_confidence TEXT,
    category_hints JSONB
)
LANGUAGE sql
STABLE
AS $$
SELECT
    v.id AS video_id,
    v.external_id,
    v.channel_name,
    v.title,
    left(COALESCE(v.description, ''), GREATEST(p_description_max_chars, 0)) AS description,
    v.published_at,
    v.duration_seconds,
    v.language,
    v.region,
    v.short_confidence,
    COALESCE(hints.category_hints, '[]'::jsonb) AS category_hints
  FROM videos v
  LEFT JOIN LATERAL (
      SELECT jsonb_agg(DISTINCT c.slug ORDER BY c.slug) AS category_hints
        FROM video_collection_matches m
        JOIN collection_queries q ON q.id = m.collection_query_id
        JOIN categories c ON c.id = q.category_id
       WHERE m.video_id = v.id
  ) hints ON TRUE
 WHERE v.platform = 'youtube'
   AND NOT EXISTS (
       SELECT 1
         FROM video_classifications classification
        WHERE classification.video_id = v.id
   )
 ORDER BY v.published_at DESC, v.id
 LIMIT GREATEST(p_limit, 0);
$$;

CREATE OR REPLACE FUNCTION refresh_video_metrics(
    p_limit INTEGER,
    p_as_of TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
)
RETURNS TABLE (
    eligible_videos BIGINT,
    candidates_selected BIGINT,
    metrics_upserted BIGINT,
    virality_scored BIGINT,
    velocity_available BIGINT,
    acceleration_available BIGINT,
    channel_baseline_available BIGINT,
    calculation_version TEXT,
    calculated_at TIMESTAMPTZ
)
LANGUAGE sql
VOLATILE
AS $$
WITH config AS (
    SELECT
        COALESCE(MAX(value #>> '{}') FILTER (WHERE key = 'METRICS_CALCULATION_VERSION'), 'v1') AS calculation_version,
        GREATEST(COALESCE(MAX((value #>> '{}')::INTEGER) FILTER (WHERE key = 'METRICS_ANALYSIS_WINDOW_DAYS'), 7), 0) AS analysis_window_days,
        GREATEST(COALESCE(MAX((value #>> '{}')::INTEGER) FILTER (WHERE key = 'METRICS_CHANNEL_BASELINE_WINDOW_DAYS'), 30), 0) AS baseline_window_days,
        GREATEST(COALESCE(MAX((value #>> '{}')::INTEGER) FILTER (WHERE key = 'METRICS_CHANNEL_BASELINE_MIN_VIDEOS'), 3), 1) AS baseline_min_videos,
        GREATEST(COALESCE(MAX((value #>> '{}')::NUMERIC) FILTER (WHERE key = 'METRICS_FRESHNESS_HORIZON_HOURS'), 168), 0) AS freshness_horizon_hours,
        GREATEST(COALESCE(MAX((value #>> '{}')::INTEGER) FILTER (WHERE key = 'METRICS_MIN_VIRALITY_COMPONENTS'), 3), 1) AS min_virality_components,
        GREATEST(COALESCE(MAX((value #>> '{}')::INTEGER) FILTER (WHERE key = 'MIN_SAMPLE_SIZE'), 30), 2) AS min_sample_size,
        GREATEST(COALESCE(MAX((value #>> '{}')::NUMERIC) FILTER (WHERE key = 'COMMENT_WEIGHT'), 3), 0) AS comment_weight,
        GREATEST(COALESCE(MAX((value #>> '{}')::NUMERIC) FILTER (WHERE key = 'VIRALITY_VELOCITY_WEIGHT'), 0.35), 0) AS velocity_weight,
        GREATEST(COALESCE(MAX((value #>> '{}')::NUMERIC) FILTER (WHERE key = 'VIRALITY_ENGAGEMENT_WEIGHT'), 0.20), 0) AS engagement_weight,
        GREATEST(COALESCE(MAX((value #>> '{}')::NUMERIC) FILTER (WHERE key = 'VIRALITY_OUTLIER_WEIGHT'), 0.20), 0) AS outlier_weight,
        GREATEST(COALESCE(MAX((value #>> '{}')::NUMERIC) FILTER (WHERE key = 'VIRALITY_VIEWS_WEIGHT'), 0.15), 0) AS views_weight,
        GREATEST(COALESCE(MAX((value #>> '{}')::NUMERIC) FILTER (WHERE key = 'VIRALITY_FRESHNESS_WEIGHT'), 0.10), 0) AS freshness_weight
      FROM settings
), snapshot_history AS (
    SELECT
        snapshot.*,
        lag(snapshot.id) OVER snapshot_order AS previous_snapshot_id,
        lag(snapshot.views) OVER snapshot_order AS previous_views,
        lag(snapshot.collected_at) OVER snapshot_order AS previous_collected_at,
        lag(snapshot.views, 2) OVER snapshot_order AS second_previous_views,
        lag(snapshot.collected_at, 2) OVER snapshot_order AS second_previous_collected_at
      FROM video_snapshots snapshot
    WINDOW snapshot_order AS (
        PARTITION BY snapshot.video_id
        ORDER BY snapshot.collected_at, snapshot.id
    )
), latest_snapshots AS (
    SELECT DISTINCT ON (video.id)
        video.id AS video_id,
        video.platform,
        video.channel_id,
        video.published_at,
        video.region,
        classification.category_id,
        history.id AS snapshot_id,
        history.collected_at,
        history.views,
        history.likes,
        history.comments,
        history.previous_snapshot_id,
        history.previous_views,
        history.previous_collected_at,
        history.second_previous_views,
        history.second_previous_collected_at
      FROM videos video
      CROSS JOIN config
      JOIN snapshot_history history ON history.video_id = video.id
      LEFT JOIN video_classifications classification ON classification.video_id = video.id
     WHERE video.platform = 'youtube'
       AND video.published_at <= p_as_of
       AND video.published_at >= p_as_of - make_interval(days => config.analysis_window_days)
       AND history.collected_at <= p_as_of
     ORDER BY video.id, history.collected_at DESC, history.id DESC
), ordered_targets AS (
    SELECT
        latest_snapshots.snapshot_id,
        row_number() OVER (
            ORDER BY
                (metrics.snapshot_id IS NULL OR metrics.calculation_version <> config.calculation_version) DESC,
                latest_snapshots.collected_at DESC,
                latest_snapshots.snapshot_id
        ) AS target_order
      FROM latest_snapshots
      CROSS JOIN config
      LEFT JOIN video_metrics metrics ON metrics.snapshot_id = latest_snapshots.snapshot_id
), targets AS (
    SELECT snapshot_id
      FROM ordered_targets
     WHERE target_order <= GREATEST(p_limit, 0)
), metric_basis AS (
    SELECT
        latest.*,
        CASE
            WHEN latest.views > 0 AND latest.likes IS NOT NULL
                THEN latest.likes::NUMERIC / latest.views
            ELSE NULL
        END AS like_rate,
        CASE
            WHEN latest.views > 0 AND latest.comments IS NOT NULL
                THEN latest.comments::NUMERIC / latest.views
            ELSE NULL
        END AS comment_rate,
        CASE
            WHEN latest.views > 0 AND latest.likes IS NOT NULL AND latest.comments IS NOT NULL
                THEN (latest.likes + (latest.comments * config.comment_weight))::NUMERIC / latest.views
            ELSE NULL
        END AS engagement_rate,
        CASE
            WHEN latest.previous_snapshot_id IS NOT NULL
             AND latest.collected_at > latest.previous_collected_at
                THEN (latest.views - latest.previous_views)::NUMERIC
                     / (EXTRACT(EPOCH FROM (latest.collected_at - latest.previous_collected_at)) / 3600.0)
            ELSE NULL
        END AS view_velocity,
        CASE
            WHEN latest.second_previous_collected_at IS NOT NULL
             AND latest.previous_collected_at > latest.second_previous_collected_at
                THEN (latest.previous_views - latest.second_previous_views)::NUMERIC
                     / (EXTRACT(EPOCH FROM (latest.previous_collected_at - latest.second_previous_collected_at)) / 3600.0)
            ELSE NULL
        END AS previous_view_velocity,
        CASE
            WHEN config.freshness_horizon_hours > 0 THEN
                GREATEST(
                    0::NUMERIC,
                    LEAST(
                        1::NUMERIC,
                        1 - (EXTRACT(EPOCH FROM (p_as_of - latest.published_at)) / 3600.0)
                            / config.freshness_horizon_hours
                    )
                )
            ELSE NULL
        END AS freshness_score,
        baseline.sample_size AS channel_baseline_sample_size,
        CASE
            WHEN baseline.sample_size >= config.baseline_min_videos
                THEN baseline.median_views
            ELSE NULL
        END AS channel_median_views
      FROM latest_snapshots latest
      CROSS JOIN config
      LEFT JOIN LATERAL (
          SELECT
              count(*)::INTEGER AS sample_size,
              percentile_cont(0.5) WITHIN GROUP (ORDER BY sample.views)::NUMERIC AS median_views
            FROM (
                SELECT DISTINCT ON (baseline_video.id)
                    baseline_snapshot.views
                  FROM videos baseline_video
                  JOIN video_snapshots baseline_snapshot ON baseline_snapshot.video_id = baseline_video.id
                 WHERE baseline_video.platform = latest.platform
                   AND baseline_video.channel_id = latest.channel_id
                   AND length(btrim(baseline_video.channel_id)) > 0
                   AND baseline_video.id <> latest.video_id
                   AND baseline_video.published_at <= p_as_of
                   AND baseline_video.published_at >= p_as_of - make_interval(days => config.baseline_window_days)
                   AND baseline_snapshot.collected_at <= p_as_of
                 ORDER BY baseline_video.id, baseline_snapshot.collected_at DESC, baseline_snapshot.id DESC
            ) sample
      ) baseline ON TRUE
), raw_metrics AS (
    SELECT
        metric_basis.*,
        CASE
            WHEN metric_basis.view_velocity IS NOT NULL
             AND metric_basis.previous_view_velocity IS NOT NULL
             AND metric_basis.collected_at > metric_basis.previous_collected_at
                THEN (metric_basis.view_velocity - metric_basis.previous_view_velocity)
                     / (EXTRACT(EPOCH FROM (metric_basis.collected_at - metric_basis.previous_collected_at)) / 3600.0)
            ELSE NULL
        END AS view_acceleration,
        CASE
            WHEN metric_basis.channel_median_views > 0
                THEN metric_basis.views::NUMERIC / metric_basis.channel_median_views
            ELSE NULL
        END AS relative_performance,
        CASE
            WHEN metric_basis.channel_median_views > 0
                THEN metric_basis.views::NUMERIC / metric_basis.channel_median_views
            ELSE NULL
        END AS outlier_score
      FROM metric_basis
), fallback_views AS (
    SELECT
        snapshot_id,
        count(*) OVER (PARTITION BY platform, region) AS sample_size,
        percent_rank() OVER (PARTITION BY platform, region ORDER BY views) AS percentile
      FROM raw_metrics
), category_views AS (
    SELECT
        snapshot_id,
        count(*) OVER (PARTITION BY platform, region, category_id) AS sample_size,
        percent_rank() OVER (PARTITION BY platform, region, category_id ORDER BY views) AS percentile
      FROM raw_metrics
     WHERE category_id IS NOT NULL
), fallback_velocity AS (
    SELECT
        snapshot_id,
        count(*) OVER (PARTITION BY platform, region) AS sample_size,
        percent_rank() OVER (PARTITION BY platform, region ORDER BY view_velocity) AS percentile
      FROM raw_metrics
     WHERE view_velocity IS NOT NULL
), category_velocity AS (
    SELECT
        snapshot_id,
        count(*) OVER (PARTITION BY platform, region, category_id) AS sample_size,
        percent_rank() OVER (PARTITION BY platform, region, category_id ORDER BY view_velocity) AS percentile
      FROM raw_metrics
     WHERE category_id IS NOT NULL AND view_velocity IS NOT NULL
), fallback_engagement AS (
    SELECT
        snapshot_id,
        count(*) OVER (PARTITION BY platform, region) AS sample_size,
        percent_rank() OVER (PARTITION BY platform, region ORDER BY engagement_rate) AS percentile
      FROM raw_metrics
     WHERE engagement_rate IS NOT NULL
), category_engagement AS (
    SELECT
        snapshot_id,
        count(*) OVER (PARTITION BY platform, region, category_id) AS sample_size,
        percent_rank() OVER (PARTITION BY platform, region, category_id ORDER BY engagement_rate) AS percentile
      FROM raw_metrics
     WHERE category_id IS NOT NULL AND engagement_rate IS NOT NULL
), fallback_outlier AS (
    SELECT
        snapshot_id,
        count(*) OVER (PARTITION BY platform, region) AS sample_size,
        percent_rank() OVER (PARTITION BY platform, region ORDER BY outlier_score) AS percentile
      FROM raw_metrics
     WHERE outlier_score IS NOT NULL
), category_outlier AS (
    SELECT
        snapshot_id,
        count(*) OVER (PARTITION BY platform, region, category_id) AS sample_size,
        percent_rank() OVER (PARTITION BY platform, region, category_id ORDER BY outlier_score) AS percentile
      FROM raw_metrics
     WHERE category_id IS NOT NULL AND outlier_score IS NOT NULL
), percentile_metrics AS (
    SELECT
        raw_metrics.*,
        CASE
            WHEN category_velocity.sample_size >= config.min_sample_size THEN category_velocity.percentile
            WHEN fallback_velocity.sample_size >= config.min_sample_size THEN fallback_velocity.percentile
            ELSE NULL
        END::NUMERIC AS velocity_percentile,
        CASE
            WHEN category_engagement.sample_size >= config.min_sample_size THEN category_engagement.percentile
            WHEN fallback_engagement.sample_size >= config.min_sample_size THEN fallback_engagement.percentile
            ELSE NULL
        END::NUMERIC AS engagement_percentile,
        CASE
            WHEN category_outlier.sample_size >= config.min_sample_size THEN category_outlier.percentile
            WHEN fallback_outlier.sample_size >= config.min_sample_size THEN fallback_outlier.percentile
            ELSE NULL
        END::NUMERIC AS outlier_percentile,
        CASE
            WHEN category_views.sample_size >= config.min_sample_size THEN category_views.percentile
            WHEN fallback_views.sample_size >= config.min_sample_size THEN fallback_views.percentile
            ELSE NULL
        END::NUMERIC AS views_percentile
      FROM raw_metrics
      CROSS JOIN config
      JOIN fallback_views USING (snapshot_id)
      LEFT JOIN category_views USING (snapshot_id)
      LEFT JOIN fallback_velocity USING (snapshot_id)
      LEFT JOIN category_velocity USING (snapshot_id)
      LEFT JOIN fallback_engagement USING (snapshot_id)
      LEFT JOIN category_engagement USING (snapshot_id)
      LEFT JOIN fallback_outlier USING (snapshot_id)
      LEFT JOIN category_outlier USING (snapshot_id)
), score_components AS (
    SELECT
        percentile_metrics.*,
        num_nonnulls(
            velocity_percentile,
            engagement_percentile,
            outlier_percentile,
            views_percentile,
            freshness_score
        ) AS component_count,
        (CASE WHEN velocity_percentile IS NOT NULL THEN config.velocity_weight ELSE 0 END
         + CASE WHEN engagement_percentile IS NOT NULL THEN config.engagement_weight ELSE 0 END
         + CASE WHEN outlier_percentile IS NOT NULL THEN config.outlier_weight ELSE 0 END
         + CASE WHEN views_percentile IS NOT NULL THEN config.views_weight ELSE 0 END
         + CASE WHEN freshness_score IS NOT NULL THEN config.freshness_weight ELSE 0 END) AS available_weight,
        (COALESCE(velocity_percentile * config.velocity_weight, 0)
         + COALESCE(engagement_percentile * config.engagement_weight, 0)
         + COALESCE(outlier_percentile * config.outlier_weight, 0)
         + COALESCE(views_percentile * config.views_weight, 0)
         + COALESCE(freshness_score * config.freshness_weight, 0)) AS weighted_score
      FROM percentile_metrics
      CROSS JOIN config
), scored AS (
    SELECT
        score_components.*,
        CASE
            WHEN component_count >= config.min_virality_components
             AND available_weight > 0
                THEN round(10 * weighted_score / available_weight, 4)
            ELSE NULL
        END AS virality_score
      FROM score_components
      CROSS JOIN config
), upserted AS (
    INSERT INTO video_metrics (
        video_id,
        snapshot_id,
        previous_snapshot_id,
        like_rate,
        comment_rate,
        engagement_rate,
        view_velocity,
        view_acceleration,
        channel_median_views,
        relative_performance,
        outlier_score,
        velocity_percentile,
        engagement_percentile,
        outlier_percentile,
        views_percentile,
        freshness_score,
        virality_score,
        calculation_version,
        calculated_at
    )
    SELECT
        scored.video_id,
        scored.snapshot_id,
        scored.previous_snapshot_id,
        scored.like_rate,
        scored.comment_rate,
        scored.engagement_rate,
        scored.view_velocity,
        scored.view_acceleration,
        scored.channel_median_views,
        scored.relative_performance,
        scored.outlier_score,
        scored.velocity_percentile,
        scored.engagement_percentile,
        scored.outlier_percentile,
        scored.views_percentile,
        scored.freshness_score,
        scored.virality_score,
        config.calculation_version,
        p_as_of
      FROM scored
      JOIN targets USING (snapshot_id)
      CROSS JOIN config
    ON CONFLICT (snapshot_id) DO UPDATE
    SET
        video_id = EXCLUDED.video_id,
        previous_snapshot_id = EXCLUDED.previous_snapshot_id,
        like_rate = EXCLUDED.like_rate,
        comment_rate = EXCLUDED.comment_rate,
        engagement_rate = EXCLUDED.engagement_rate,
        view_velocity = EXCLUDED.view_velocity,
        view_acceleration = EXCLUDED.view_acceleration,
        channel_median_views = EXCLUDED.channel_median_views,
        relative_performance = EXCLUDED.relative_performance,
        outlier_score = EXCLUDED.outlier_score,
        velocity_percentile = EXCLUDED.velocity_percentile,
        engagement_percentile = EXCLUDED.engagement_percentile,
        outlier_percentile = EXCLUDED.outlier_percentile,
        views_percentile = EXCLUDED.views_percentile,
        freshness_score = EXCLUDED.freshness_score,
        virality_score = EXCLUDED.virality_score,
        calculation_version = EXCLUDED.calculation_version,
        calculated_at = EXCLUDED.calculated_at
    RETURNING
        snapshot_id,
        view_velocity,
        view_acceleration,
        channel_median_views,
        virality_score
)
SELECT
    (SELECT count(*) FROM latest_snapshots) AS eligible_videos,
    (SELECT count(*) FROM targets) AS candidates_selected,
    (SELECT count(*) FROM upserted) AS metrics_upserted,
    (SELECT count(*) FROM upserted WHERE virality_score IS NOT NULL) AS virality_scored,
    (SELECT count(*) FROM upserted WHERE view_velocity IS NOT NULL) AS velocity_available,
    (SELECT count(*) FROM upserted WHERE view_acceleration IS NOT NULL) AS acceleration_available,
    (SELECT count(*) FROM upserted WHERE channel_median_views IS NOT NULL) AS channel_baseline_available,
    config.calculation_version,
    p_as_of AS calculated_at
  FROM config;
$$;

CREATE OR REPLACE FUNCTION refresh_video_monetization_scores(
    p_limit INTEGER,
    p_as_of TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
)
RETURNS TABLE (
    eligible_classifications BIGINT,
    candidates_selected BIGINT,
    scores_upserted BIGINT,
    engagement_quality_available BIGINT,
    high_risk_scores BIGINT,
    calculation_version TEXT,
    calculated_at TIMESTAMPTZ
)
LANGUAGE sql
VOLATILE
AS $$
WITH config AS (
    SELECT
        COALESCE((SELECT value #>> '{}' FROM settings WHERE key = 'MONETIZATION_CALCULATION_VERSION'), 'v1') AS calculation_version,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'MONETIZATION_ORIGINALITY_WEIGHT'), 0.30), 0) AS originality_weight,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'MONETIZATION_POLICY_WEIGHT'), 0.25), 0) AS policy_weight,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'MONETIZATION_ADVERTISER_WEIGHT'), 0.15), 0) AS advertiser_weight,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'MONETIZATION_PRODUCTION_WEIGHT'), 0.15), 0) AS production_weight,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'MONETIZATION_ENGAGEMENT_WEIGHT'), 0.15), 0) AS engagement_weight,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'MONETIZATION_COPYRIGHT_RISK_WEIGHT'), 0.60), 0) AS copyright_weight,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'MONETIZATION_REUSED_RISK_WEIGHT'), 0.40), 0) AS reused_weight,
        GREATEST(0::NUMERIC, LEAST(1::NUMERIC, COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'MONETIZATION_PRODUCTION_DURATION_WEIGHT'), 0.30))) AS duration_weight,
        GREATEST(0::NUMERIC, LEAST(1::NUMERIC, COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'MONETIZATION_HIGH_RISK_THRESHOLD'), 0.70))) AS high_risk_threshold,
        COALESCE(
            (SELECT value FROM settings WHERE key = 'MONETIZATION_POLICY_SOURCE_SCORES'),
            '{"original":1.0,"user_generated":0.9,"stock_media":0.8,"gameplay":0.75,"reaction":0.65,"podcast_clip":0.45,"third_party_content":0.35,"compilation":0.25,"movie_or_tv_clip":0.15,"unknown":0.5}'::JSONB
        ) AS policy_source_scores,
        COALESCE(
            (SELECT value FROM settings WHERE key = 'MONETIZATION_ADVERTISER_FORMAT_SCORES'),
            '{"tutorial":0.95,"explainer":0.9,"curiosity":0.85,"comparison":0.85,"ranking":0.8,"storytelling":0.8,"motivation":0.85,"commentary":0.75,"news":0.65,"reaction":0.65,"meme":0.6,"clip":0.55,"compilation":0.55,"unknown":0.5}'::JSONB
        ) AS advertiser_format_scores,
        COALESCE(
            (SELECT value FROM settings WHERE key = 'MONETIZATION_PRODUCTION_FORMAT_SCORES'),
            '{"clip":0.95,"meme":0.9,"reaction":0.85,"compilation":0.85,"ranking":0.8,"curiosity":0.75,"motivation":0.75,"commentary":0.7,"comparison":0.7,"news":0.7,"explainer":0.65,"storytelling":0.65,"tutorial":0.6,"unknown":0.5}'::JSONB
        ) AS production_format_scores
), classified AS (
    SELECT
        classification.*,
        video.duration_seconds,
        metric.engagement_percentile,
        metric.calculated_at AS metric_calculated_at
      FROM video_classifications classification
      JOIN videos video ON video.id = classification.video_id
      LEFT JOIN LATERAL (
          SELECT
              video_metric.engagement_percentile,
              video_metric.calculated_at
            FROM video_metrics video_metric
           WHERE video_metric.video_id = classification.video_id
             AND video_metric.calculated_at <= p_as_of
           ORDER BY video_metric.calculated_at DESC, video_metric.id DESC
           LIMIT 1
      ) metric ON TRUE
     WHERE classification.classified_at <= p_as_of
), ordered_targets AS (
    SELECT
        classified.video_id,
        row_number() OVER (
            ORDER BY
                (score.id IS NULL) DESC,
                COALESCE(classified.metric_calculated_at, classified.classified_at) DESC,
                classified.video_id
        ) AS target_order
      FROM classified
      CROSS JOIN config
      LEFT JOIN video_monetization_scores score
        ON score.video_id = classified.video_id
       AND score.calculation_version = config.calculation_version
), targets AS (
    SELECT video_id
      FROM ordered_targets
     WHERE target_order <= GREATEST(p_limit, 0)
), mapped AS (
    SELECT
        classified.*,
        config.*,
        GREATEST(
            0::NUMERIC,
            LEAST(
                1::NUMERIC,
                COALESCE(
                    NULLIF(config.policy_source_scores ->> classified.source_type, '')::NUMERIC,
                    NULLIF(config.policy_source_scores ->> 'unknown', '')::NUMERIC,
                    0.5
                )
            )
        ) AS mapped_policy,
        GREATEST(
            0::NUMERIC,
            LEAST(
                1::NUMERIC,
                COALESCE(
                    NULLIF(config.advertiser_format_scores ->> classified.format, '')::NUMERIC,
                    NULLIF(config.advertiser_format_scores ->> 'unknown', '')::NUMERIC,
                    0.5
                )
            )
        ) AS mapped_advertiser,
        GREATEST(
            0::NUMERIC,
            LEAST(
                1::NUMERIC,
                COALESCE(
                    NULLIF(config.production_format_scores ->> classified.format, '')::NUMERIC,
                    NULLIF(config.production_format_scores ->> 'unknown', '')::NUMERIC,
                    0.5
                )
            )
        ) AS mapped_production
      FROM classified
      CROSS JOIN config
), factors AS (
    SELECT
        mapped.*,
        round(mapped.originality_score, 4) AS originality,
        round(0.5 + (mapped.mapped_policy - 0.5) * mapped.ai_confidence, 4) AS policy_eligibility,
        round(0.5 + (mapped.mapped_advertiser - 0.5) * mapped.ai_confidence, 4) AS advertiser_suitability,
        round(
            CASE
                WHEN mapped.duration_seconds IS NULL THEN
                    0.5 + (mapped.mapped_production - 0.5) * mapped.ai_confidence
                ELSE
                    (1 - mapped.duration_weight)
                    * (0.5 + (mapped.mapped_production - 0.5) * mapped.ai_confidence)
                    + mapped.duration_weight
                    * CASE
                        WHEN mapped.duration_seconds <= 60 THEN 1.0
                        WHEN mapped.duration_seconds <= 120 THEN 0.8
                        WHEN mapped.duration_seconds <= 180 THEN 0.6
                        ELSE 0.4
                      END
            END,
            4
        ) AS production_feasibility,
        CASE
            WHEN mapped.engagement_percentile IS NOT NULL
                THEN round(GREATEST(0::NUMERIC, LEAST(1::NUMERIC, mapped.engagement_percentile)), 4)
            ELSE NULL
        END AS engagement_quality
      FROM mapped
), components AS (
    SELECT
        factors.*,
        (factors.originality_weight
         + factors.policy_weight
         + factors.advertiser_weight
         + factors.production_weight
         + CASE WHEN factors.engagement_quality IS NOT NULL THEN factors.engagement_weight ELSE 0 END) AS available_positive_weight,
        (factors.originality * factors.originality_weight
         + factors.policy_eligibility * factors.policy_weight
         + factors.advertiser_suitability * factors.advertiser_weight
         + factors.production_feasibility * factors.production_weight
         + COALESCE(factors.engagement_quality * factors.engagement_weight, 0)) AS weighted_positive,
        (factors.copyright_weight + factors.reused_weight) AS available_risk_weight,
        (factors.copyright_risk * factors.copyright_weight
         + factors.reused_content_risk * factors.reused_weight) AS weighted_risk
      FROM factors
), scored AS (
    SELECT
        components.*,
        CASE
            WHEN components.available_positive_weight > 0
                THEN round(components.weighted_positive / components.available_positive_weight, 4)
            ELSE NULL
        END AS positive_base,
        CASE
            WHEN components.available_risk_weight > 0
                THEN round(components.weighted_risk / components.available_risk_weight, 4)
            ELSE NULL
        END AS combined_risk
      FROM components
), final_scores AS (
    SELECT
        scored.*,
        CASE
            WHEN scored.positive_base IS NOT NULL AND scored.combined_risk IS NOT NULL
                THEN round(10 * scored.positive_base * GREATEST(0::NUMERIC, 1 - scored.combined_risk), 4)
            ELSE NULL
        END AS monetization_score
      FROM scored
), upserted AS (
    INSERT INTO video_monetization_scores (
        video_id,
        originality,
        policy_eligibility,
        advertiser_suitability,
        production_feasibility,
        engagement_quality,
        copyright_risk,
        reused_content_risk,
        positive_base,
        combined_risk,
        monetization_score,
        calculation_version,
        calculated_at
    )
    SELECT
        final_scores.video_id,
        final_scores.originality,
        final_scores.policy_eligibility,
        final_scores.advertiser_suitability,
        final_scores.production_feasibility,
        final_scores.engagement_quality,
        final_scores.copyright_risk,
        final_scores.reused_content_risk,
        final_scores.positive_base,
        final_scores.combined_risk,
        final_scores.monetization_score,
        final_scores.calculation_version,
        p_as_of
      FROM final_scores
      JOIN targets USING (video_id)
     WHERE final_scores.positive_base IS NOT NULL
       AND final_scores.combined_risk IS NOT NULL
       AND final_scores.monetization_score IS NOT NULL
    ON CONFLICT (video_id, calculation_version) DO UPDATE
    SET
        originality = EXCLUDED.originality,
        policy_eligibility = EXCLUDED.policy_eligibility,
        advertiser_suitability = EXCLUDED.advertiser_suitability,
        production_feasibility = EXCLUDED.production_feasibility,
        engagement_quality = EXCLUDED.engagement_quality,
        copyright_risk = EXCLUDED.copyright_risk,
        reused_content_risk = EXCLUDED.reused_content_risk,
        positive_base = EXCLUDED.positive_base,
        combined_risk = EXCLUDED.combined_risk,
        monetization_score = EXCLUDED.monetization_score,
        calculated_at = EXCLUDED.calculated_at
    RETURNING
        engagement_quality,
        combined_risk,
        calculation_version
)
SELECT
    (SELECT count(*) FROM classified) AS eligible_classifications,
    (SELECT count(*) FROM targets) AS candidates_selected,
    (SELECT count(*) FROM upserted) AS scores_upserted,
    (SELECT count(*) FROM upserted WHERE engagement_quality IS NOT NULL) AS engagement_quality_available,
    (SELECT count(*) FROM upserted WHERE combined_risk >= config.high_risk_threshold) AS high_risk_scores,
    config.calculation_version,
    p_as_of AS calculated_at
  FROM config;
$$;

CREATE OR REPLACE FUNCTION refresh_category_statistics(
    p_as_of TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
)
RETURNS TABLE (
    videos_in_current_period BIGINT,
    dimension_rows BIGINT,
    statistics_upserted BIGINT,
    sufficient_sample_statistics BIGINT,
    rising_statistics BIGINT,
    stable_statistics BIGINT,
    declining_statistics BIGINT,
    insufficient_statistics BIGINT,
    calculation_version TEXT,
    period_start TIMESTAMPTZ,
    period_end TIMESTAMPTZ
)
LANGUAGE sql
VOLATILE
AS $$
WITH config AS (
    SELECT
        GREATEST(COALESCE((SELECT (value #>> '{}')::INTEGER FROM settings WHERE key = 'TREND_PERIOD_HOURS'), 168), 1) AS period_hours,
        GREATEST(COALESCE((SELECT (value #>> '{}')::INTEGER FROM settings WHERE key = 'TREND_BUCKET_MINUTES'), 60), 1) AS bucket_minutes,
        GREATEST(COALESCE((SELECT (value #>> '{}')::INTEGER FROM settings WHERE key = 'TREND_MIN_SAMPLE_SIZE'), 30), 1) AS min_sample_size,
        COALESCE((SELECT value #>> '{}' FROM settings WHERE key = 'TREND_CALCULATION_VERSION'), 'v1') AS calculation_version,
        GREATEST(0::NUMERIC, LEAST(1::NUMERIC, COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'TREND_OUTLIER_PERCENTILE_THRESHOLD'), 0.90))) AS outlier_threshold,
        GREATEST(0::NUMERIC, LEAST(10::NUMERIC, COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'TREND_HIGH_VIRALITY_THRESHOLD'), 7.0))) AS high_virality_threshold,
        GREATEST(0::NUMERIC, LEAST(1::NUMERIC, COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'TREND_DIRECTION_CHANGE_THRESHOLD'), 0.10))) AS direction_threshold,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'CONSISTENCY_SAMPLE_WEIGHT'), 0.20), 0) AS sample_weight,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'CONSISTENCY_P75_WEIGHT'), 0.30), 0) AS p75_weight,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'CONSISTENCY_P90_WEIGHT'), 0.20), 0) AS p90_weight,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'CONSISTENCY_ENGAGEMENT_WEIGHT'), 0.20), 0) AS engagement_weight,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'CONSISTENCY_DISPERSION_WEIGHT'), 0.10), 0) AS dispersion_weight,
        COALESCE((SELECT value #>> '{}' FROM settings WHERE key = 'METRICS_CALCULATION_VERSION'), 'v1') AS metrics_version,
        COALESCE((SELECT value #>> '{}' FROM settings WHERE key = 'MONETIZATION_CALCULATION_VERSION'), 'v1') AS monetization_version
), bucketed AS (
    SELECT
        config.*,
        date_bin(
            make_interval(mins => config.bucket_minutes),
            p_as_of,
            TIMESTAMPTZ '2000-01-01 00:00:00+00'
        ) AS bucket_floor
      FROM config
), bounds AS (
    SELECT
        bucketed.*,
        CASE
            WHEN bucketed.bucket_floor = p_as_of THEN p_as_of
            ELSE bucketed.bucket_floor + make_interval(mins => bucketed.bucket_minutes)
        END AS period_end,
        CASE
            WHEN bucketed.bucket_floor = p_as_of THEN p_as_of
            ELSE bucketed.bucket_floor + make_interval(mins => bucketed.bucket_minutes)
        END - make_interval(hours => bucketed.period_hours) AS period_start,
        CASE
            WHEN bucketed.bucket_floor = p_as_of THEN p_as_of
            ELSE bucketed.bucket_floor + make_interval(mins => bucketed.bucket_minutes)
        END - make_interval(hours => bucketed.period_hours * 2) AS previous_period_start
      FROM bucketed
), period_videos AS (
    SELECT
        period_window.window_name,
        video.id AS video_id,
        video.platform,
        video.region,
        video.language,
        category.slug AS category_slug,
        classification.topic,
        classification.content_type,
        classification.format,
        classification.hook_type,
        classification.source_type,
        snapshot.views,
        metric.engagement_rate,
        metric.view_velocity,
        metric.outlier_percentile,
        metric.views_percentile,
        metric.engagement_percentile,
        metric.virality_score,
        monetization.monetization_score
      FROM bounds
      CROSS JOIN LATERAL (
          VALUES
              ('current'::TEXT, bounds.period_start, bounds.period_end),
              ('previous'::TEXT, bounds.previous_period_start, bounds.period_start)
      ) period_window (window_name, window_start, window_end)
      JOIN videos video
        ON video.published_at >= period_window.window_start
       AND video.published_at < period_window.window_end
      JOIN video_classifications classification
        ON classification.video_id = video.id
      LEFT JOIN categories category ON category.id = classification.category_id
      JOIN LATERAL (
          SELECT video_snapshot.*
            FROM video_snapshots video_snapshot
           WHERE video_snapshot.video_id = video.id
             AND video_snapshot.collected_at < period_window.window_end
           ORDER BY video_snapshot.collected_at DESC, video_snapshot.id DESC
           LIMIT 1
      ) snapshot ON TRUE
      LEFT JOIN video_metrics metric
        ON metric.snapshot_id = snapshot.id
       AND metric.calculation_version = bounds.metrics_version
      LEFT JOIN video_monetization_scores monetization
        ON monetization.video_id = video.id
       AND monetization.calculation_version = bounds.monetization_version
), dimensioned AS (
    SELECT
        period_videos.*,
        dimension.dimension_type,
        dimension.dimension_value
      FROM period_videos
      CROSS JOIN LATERAL (
          VALUES
              ('category'::TEXT, period_videos.category_slug),
              ('topic'::TEXT, period_videos.topic),
              ('content_type'::TEXT, period_videos.content_type),
              ('format'::TEXT, period_videos.format),
              ('hook_type'::TEXT, period_videos.hook_type),
              ('source_type'::TEXT, period_videos.source_type),
              (
                  'category_format_source'::TEXT,
                  CASE
                      WHEN period_videos.category_slug IS NOT NULL THEN
                          period_videos.category_slug || '|' || period_videos.format || '|' || period_videos.source_type
                      ELSE NULL
                  END
              )
      ) dimension (dimension_type, dimension_value)
     WHERE dimension.dimension_value IS NOT NULL
       AND length(btrim(dimension.dimension_value)) > 0
), raw_aggregates AS (
    SELECT
        dimensioned.window_name,
        dimensioned.platform,
        dimensioned.region,
        dimensioned.language,
        dimensioned.dimension_type,
        dimensioned.dimension_value,
        count(*)::INTEGER AS sample_size,
        percentile_cont(0.5) WITHIN GROUP (ORDER BY dimensioned.views)::NUMERIC AS median_views,
        percentile_cont(0.75) WITHIN GROUP (ORDER BY dimensioned.views)::NUMERIC AS p75_views,
        percentile_cont(0.90) WITHIN GROUP (ORDER BY dimensioned.views)::NUMERIC AS p90_views,
        percentile_cont(0.5) WITHIN GROUP (ORDER BY dimensioned.engagement_rate)::NUMERIC AS median_engagement,
        percentile_cont(0.5) WITHIN GROUP (ORDER BY dimensioned.view_velocity)::NUMERIC AS median_velocity,
        percentile_cont(0.5) WITHIN GROUP (ORDER BY dimensioned.virality_score)::NUMERIC AS median_virality,
        percentile_cont(0.5) WITHIN GROUP (ORDER BY dimensioned.monetization_score)::NUMERIC AS median_monetization,
        percentile_cont(0.5) WITHIN GROUP (ORDER BY dimensioned.engagement_percentile)::NUMERIC AS median_engagement_percentile,
        count(*) FILTER (WHERE dimensioned.outlier_percentile >= bounds.outlier_threshold)::INTEGER AS outlier_count,
        count(dimensioned.outlier_percentile)::INTEGER AS outlier_available,
        count(*) FILTER (WHERE dimensioned.virality_score >= bounds.high_virality_threshold)::INTEGER AS high_performance_count,
        count(dimensioned.virality_score)::INTEGER AS virality_available,
        count(*) FILTER (WHERE dimensioned.views_percentile >= 0.75)::INTEGER AS p75_count,
        count(*) FILTER (WHERE dimensioned.views_percentile >= 0.90)::INTEGER AS p90_count,
        count(dimensioned.views_percentile)::INTEGER AS views_percentile_available
      FROM dimensioned
      CROSS JOIN bounds
     GROUP BY
        dimensioned.window_name,
        dimensioned.platform,
        dimensioned.region,
        dimensioned.language,
        dimensioned.dimension_type,
        dimensioned.dimension_value
), derived_aggregates AS (
    SELECT
        raw_aggregates.*,
        CASE
            WHEN raw_aggregates.outlier_available > 0
                THEN round(raw_aggregates.outlier_count::NUMERIC / raw_aggregates.outlier_available, 4)
            ELSE NULL
        END AS outlier_rate,
        CASE
            WHEN raw_aggregates.virality_available > 0
                THEN round(raw_aggregates.high_performance_count::NUMERIC / raw_aggregates.virality_available, 4)
            ELSE NULL
        END AS high_performance_rate,
        CASE
            WHEN raw_aggregates.views_percentile_available > 0
                THEN round(raw_aggregates.p75_count::NUMERIC / raw_aggregates.views_percentile_available, 4)
            ELSE NULL
        END AS p75_performance_rate,
        CASE
            WHEN raw_aggregates.views_percentile_available > 0
                THEN round(raw_aggregates.p90_count::NUMERIC / raw_aggregates.views_percentile_available, 4)
            ELSE NULL
        END AS p90_performance_rate,
        CASE
            WHEN raw_aggregates.median_views IS NOT NULL AND raw_aggregates.p90_views IS NOT NULL THEN
                round(
                    GREATEST(
                        0::NUMERIC,
                        1 - LEAST(
                            1::NUMERIC,
                            (raw_aggregates.p90_views - raw_aggregates.median_views)
                            / GREATEST(raw_aggregates.median_views, 1)
                        )
                    ),
                    4
                )
            ELSE NULL
        END AS dispersion_score
      FROM raw_aggregates
), consistency_components AS (
    SELECT
        derived_aggregates.*,
        LEAST(1::NUMERIC, derived_aggregates.sample_size::NUMERIC / bounds.min_sample_size) AS sample_adequacy,
        (bounds.sample_weight
         + CASE WHEN derived_aggregates.p75_performance_rate IS NOT NULL THEN bounds.p75_weight ELSE 0 END
         + CASE WHEN derived_aggregates.p90_performance_rate IS NOT NULL THEN bounds.p90_weight ELSE 0 END
         + CASE WHEN derived_aggregates.median_engagement_percentile IS NOT NULL THEN bounds.engagement_weight ELSE 0 END
         + CASE WHEN derived_aggregates.dispersion_score IS NOT NULL THEN bounds.dispersion_weight ELSE 0 END) AS available_consistency_weight,
        (LEAST(1::NUMERIC, derived_aggregates.sample_size::NUMERIC / bounds.min_sample_size) * bounds.sample_weight
         + COALESCE(derived_aggregates.p75_performance_rate * bounds.p75_weight, 0)
         + COALESCE(derived_aggregates.p90_performance_rate * bounds.p90_weight, 0)
         + COALESCE(derived_aggregates.median_engagement_percentile * bounds.engagement_weight, 0)
         + COALESCE(derived_aggregates.dispersion_score * bounds.dispersion_weight, 0)) AS weighted_consistency
      FROM derived_aggregates
      CROSS JOIN bounds
), scored_aggregates AS (
    SELECT
        consistency_components.*,
        CASE
            WHEN consistency_components.available_consistency_weight > 0
                THEN round(10 * consistency_components.weighted_consistency / consistency_components.available_consistency_weight, 4)
            ELSE NULL
        END AS consistency_score
      FROM consistency_components
), compared AS (
    SELECT
        current_group.*,
        COALESCE(previous_group.sample_size, 0) AS previous_sample_size,
        CASE
            WHEN current_group.sample_size >= bounds.min_sample_size
             AND COALESCE(previous_group.sample_size, 0) >= bounds.min_sample_size
             AND current_group.median_virality IS NOT NULL
             AND previous_group.median_virality IS NOT NULL
                THEN round((current_group.median_virality - previous_group.median_virality) / 10, 6)
            ELSE NULL
        END AS trend_change
      FROM scored_aggregates current_group
      CROSS JOIN bounds
      LEFT JOIN scored_aggregates previous_group
        ON previous_group.window_name = 'previous'
       AND previous_group.platform = current_group.platform
       AND previous_group.region IS NOT DISTINCT FROM current_group.region
       AND previous_group.language IS NOT DISTINCT FROM current_group.language
       AND previous_group.dimension_type = current_group.dimension_type
       AND previous_group.dimension_value = current_group.dimension_value
     WHERE current_group.window_name = 'current'
), final_statistics AS (
    SELECT
        compared.*,
        CASE
            WHEN compared.trend_change IS NULL THEN 'insufficient_data'
            WHEN compared.trend_change >= bounds.direction_threshold THEN 'rising'
            WHEN compared.trend_change <= -bounds.direction_threshold THEN 'declining'
            ELSE 'stable'
        END AS trend_direction
      FROM compared
      CROSS JOIN bounds
), upserted AS (
    INSERT INTO category_statistics (
        period_start,
        period_end,
        platform,
        region,
        language,
        category_slug,
        dimension_type,
        dimension_value,
        topic,
        content_type,
        format,
        hook_type,
        source_type,
        sample_size,
        median_views,
        p75_views,
        p90_views,
        median_engagement,
        median_velocity,
        median_virality,
        median_monetization,
        outlier_count,
        outlier_rate,
        high_performance_rate,
        p75_performance_rate,
        p90_performance_rate,
        dispersion_score,
        consistency_score,
        saturation_score,
        opportunity_score,
        previous_sample_size,
        trend_change,
        trend_direction,
        calculation_version,
        created_at
    )
    SELECT
        bounds.period_start,
        bounds.period_end,
        final_statistics.platform,
        final_statistics.region,
        final_statistics.language,
        CASE
            WHEN final_statistics.dimension_type = 'category' THEN final_statistics.dimension_value
            WHEN final_statistics.dimension_type = 'category_format_source' THEN split_part(final_statistics.dimension_value, '|', 1)
            ELSE NULL
        END,
        final_statistics.dimension_type,
        final_statistics.dimension_value,
        CASE WHEN final_statistics.dimension_type = 'topic' THEN final_statistics.dimension_value ELSE NULL END,
        CASE WHEN final_statistics.dimension_type = 'content_type' THEN final_statistics.dimension_value ELSE NULL END,
        CASE
            WHEN final_statistics.dimension_type = 'format' THEN final_statistics.dimension_value
            WHEN final_statistics.dimension_type = 'category_format_source' THEN split_part(final_statistics.dimension_value, '|', 2)
            ELSE NULL
        END,
        CASE WHEN final_statistics.dimension_type = 'hook_type' THEN final_statistics.dimension_value ELSE NULL END,
        CASE
            WHEN final_statistics.dimension_type = 'source_type' THEN final_statistics.dimension_value
            WHEN final_statistics.dimension_type = 'category_format_source' THEN split_part(final_statistics.dimension_value, '|', 3)
            ELSE NULL
        END,
        final_statistics.sample_size,
        final_statistics.median_views,
        final_statistics.p75_views,
        final_statistics.p90_views,
        final_statistics.median_engagement,
        final_statistics.median_velocity,
        final_statistics.median_virality,
        final_statistics.median_monetization,
        final_statistics.outlier_count,
        final_statistics.outlier_rate,
        final_statistics.high_performance_rate,
        final_statistics.p75_performance_rate,
        final_statistics.p90_performance_rate,
        final_statistics.dispersion_score,
        final_statistics.consistency_score,
        NULL,
        NULL,
        final_statistics.previous_sample_size,
        final_statistics.trend_change,
        final_statistics.trend_direction,
        bounds.calculation_version,
        p_as_of
      FROM final_statistics
      CROSS JOIN bounds
    ON CONFLICT (
        period_start,
        period_end,
        platform,
        region,
        language,
        dimension_type,
        dimension_value,
        calculation_version
    ) DO UPDATE
    SET
        category_slug = EXCLUDED.category_slug,
        topic = EXCLUDED.topic,
        content_type = EXCLUDED.content_type,
        format = EXCLUDED.format,
        hook_type = EXCLUDED.hook_type,
        source_type = EXCLUDED.source_type,
        sample_size = EXCLUDED.sample_size,
        median_views = EXCLUDED.median_views,
        p75_views = EXCLUDED.p75_views,
        p90_views = EXCLUDED.p90_views,
        median_engagement = EXCLUDED.median_engagement,
        median_velocity = EXCLUDED.median_velocity,
        median_virality = EXCLUDED.median_virality,
        median_monetization = EXCLUDED.median_monetization,
        outlier_count = EXCLUDED.outlier_count,
        outlier_rate = EXCLUDED.outlier_rate,
        high_performance_rate = EXCLUDED.high_performance_rate,
        p75_performance_rate = EXCLUDED.p75_performance_rate,
        p90_performance_rate = EXCLUDED.p90_performance_rate,
        dispersion_score = EXCLUDED.dispersion_score,
        consistency_score = EXCLUDED.consistency_score,
        previous_sample_size = EXCLUDED.previous_sample_size,
        trend_change = EXCLUDED.trend_change,
        trend_direction = EXCLUDED.trend_direction,
        created_at = EXCLUDED.created_at
    RETURNING
        sample_size,
        trend_direction
)
SELECT
    (SELECT count(DISTINCT video_id) FROM period_videos WHERE window_name = 'current') AS videos_in_current_period,
    (SELECT count(*) FROM final_statistics) AS dimension_rows,
    (SELECT count(*) FROM upserted) AS statistics_upserted,
    (SELECT count(*) FROM upserted WHERE sample_size >= bounds.min_sample_size) AS sufficient_sample_statistics,
    (SELECT count(*) FROM upserted WHERE trend_direction = 'rising') AS rising_statistics,
    (SELECT count(*) FROM upserted WHERE trend_direction = 'stable') AS stable_statistics,
    (SELECT count(*) FROM upserted WHERE trend_direction = 'declining') AS declining_statistics,
    (SELECT count(*) FROM upserted WHERE trend_direction = 'insufficient_data') AS insufficient_statistics,
    bounds.calculation_version,
    bounds.period_start,
    bounds.period_end
  FROM bounds;
$$;

CREATE OR REPLACE FUNCTION refresh_opportunity_rankings(
    p_as_of TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
)
RETURNS TABLE (
    statistics_considered BIGINT,
    statistics_scored BIGINT,
    statistics_incomplete BIGINT,
    categories_ranked BIGINT,
    top_opportunity_score NUMERIC,
    opportunity_calculation_version TEXT,
    trend_calculation_version TEXT,
    period_start TIMESTAMPTZ,
    period_end TIMESTAMPTZ
)
LANGUAGE sql
VOLATILE
AS $$
WITH config AS (
    SELECT
        COALESCE((SELECT value #>> '{}' FROM settings WHERE key = 'OPPORTUNITY_CALCULATION_VERSION'), 'v1') AS opportunity_version,
        COALESCE((SELECT value #>> '{}' FROM settings WHERE key = 'TREND_CALCULATION_VERSION'), 'v1') AS trend_version,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'OPPORTUNITY_VIRALITY_WEIGHT'), 0.50), 0) AS virality_weight,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'OPPORTUNITY_MONETIZATION_WEIGHT'), 0.35), 0) AS monetization_weight,
        GREATEST(COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'OPPORTUNITY_CONSISTENCY_WEIGHT'), 0.15), 0) AS consistency_weight
), latest_period AS (
    SELECT max(statistic.period_end) AS period_end
      FROM category_statistics statistic
      CROSS JOIN config
     WHERE statistic.calculation_version = config.trend_version
), target AS MATERIALIZED (
    SELECT statistic.*
      FROM category_statistics statistic
      CROSS JOIN config
      CROSS JOIN latest_period
     WHERE statistic.calculation_version = config.trend_version
       AND statistic.period_end = latest_period.period_end
), components AS (
    SELECT
        target.*,
        ((target.median_virality IS NOT NULL)::INTEGER
         + (target.median_monetization IS NOT NULL)::INTEGER
         + (target.consistency_score IS NOT NULL)::INTEGER)::SMALLINT AS component_count,
        config.opportunity_version,
        config.virality_weight,
        config.monetization_weight,
        config.consistency_weight,
        config.virality_weight + config.monetization_weight + config.consistency_weight AS available_weight
      FROM target
      CROSS JOIN config
), scored AS (
    SELECT
        components.*,
        CASE
            WHEN components.component_count = 3
             AND components.available_weight > 0
                THEN round(
                    (
                        GREATEST(0::NUMERIC, LEAST(10::NUMERIC, components.median_virality)) * components.virality_weight
                      + GREATEST(0::NUMERIC, LEAST(10::NUMERIC, components.median_monetization)) * components.monetization_weight
                      + GREATEST(0::NUMERIC, LEAST(10::NUMERIC, components.consistency_score)) * components.consistency_weight
                    ) / components.available_weight,
                    4
                )
            ELSE NULL
        END AS calculated_score
      FROM components
), ranked AS (
    SELECT
        scored.id,
        scored.calculated_score,
        dense_rank() OVER (
            PARTITION BY scored.period_start, scored.period_end, scored.platform, scored.region, scored.language, scored.dimension_type, scored.calculation_version
            ORDER BY scored.calculated_score DESC
        )::INTEGER AS calculated_rank,
        CASE
            WHEN count(*) OVER (
                PARTITION BY scored.period_start, scored.period_end, scored.platform, scored.region, scored.language, scored.dimension_type, scored.calculation_version
            ) = 1 THEN 1::NUMERIC
            ELSE round(percent_rank() OVER (
                PARTITION BY scored.period_start, scored.period_end, scored.platform, scored.region, scored.language, scored.dimension_type, scored.calculation_version
                ORDER BY scored.calculated_score ASC
            )::NUMERIC, 4)
        END AS calculated_percentile
      FROM scored
     WHERE scored.calculated_score IS NOT NULL
), updated AS (
    UPDATE category_statistics statistic
       SET opportunity_score = scored.calculated_score,
           opportunity_rank = ranked.calculated_rank,
           opportunity_percentile = ranked.calculated_percentile,
           opportunity_component_count = scored.component_count,
           opportunity_calculation_version = scored.opportunity_version,
           opportunity_calculated_at = p_as_of
      FROM scored
      LEFT JOIN ranked ON ranked.id = scored.id
     WHERE statistic.id = scored.id
    RETURNING
        statistic.dimension_type,
        statistic.opportunity_score,
        statistic.opportunity_rank,
        statistic.period_start,
        statistic.period_end
)
SELECT
    (SELECT count(*) FROM target) AS statistics_considered,
    (SELECT count(*) FROM updated WHERE opportunity_score IS NOT NULL) AS statistics_scored,
    (SELECT count(*) FROM updated WHERE opportunity_score IS NULL) AS statistics_incomplete,
    (SELECT count(*) FROM updated WHERE dimension_type = 'category' AND opportunity_score IS NOT NULL) AS categories_ranked,
    (SELECT max(opportunity_score) FROM updated WHERE dimension_type = 'category') AS top_opportunity_score,
    config.opportunity_version,
    config.trend_version,
    (SELECT min(target.period_start) FROM target),
    (SELECT max(target.period_end) FROM target)
  FROM config;
$$;

CREATE OR REPLACE FUNCTION select_recommendation_candidates(
    p_limit INTEGER DEFAULT NULL
)
RETURNS TABLE (
    category TEXT,
    period_start TIMESTAMPTZ,
    period_end TIMESTAMPTZ,
    platform TEXT,
    region CHAR(2),
    language VARCHAR(16),
    opportunity_score NUMERIC,
    virality_score NUMERIC,
    monetization_score NUMERIC,
    consistency_score NUMERIC,
    source_calculation_version TEXT,
    source_opportunity_version TEXT,
    recommendation_model TEXT,
    prompt_version TEXT,
    evidence_json JSONB,
    evidence_hash TEXT
)
LANGUAGE sql
STABLE
AS $$
WITH config AS (
    SELECT
        GREATEST(0, LEAST(50, COALESCE(p_limit, (SELECT (value #>> '{}')::INTEGER FROM settings WHERE key = 'RECOMMENDATION_MAX_CATEGORIES_PER_RUN'), 5))) AS max_categories,
        GREATEST(1, LEAST(20, COALESCE((SELECT (value #>> '{}')::INTEGER FROM settings WHERE key = 'RECOMMENDATION_CONTEXT_LIMIT'), 5))) AS context_limit,
        GREATEST(0::NUMERIC, LEAST(10::NUMERIC, COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'RECOMMENDATION_MIN_OPPORTUNITY_SCORE'), 0))) AS minimum_score,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'RECOMMENDATION_MODEL'), ''), NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'LLM_MODEL'), ''), 'nvidia/llama-3.3-nemotron-super-49b-v1') AS recommendation_model,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'RECOMMENDATION_PROMPT_VERSION'), ''), 'v2') AS prompt_version,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'TREND_CALCULATION_VERSION'), ''), 'v1') AS trend_version
), latest_period AS (
    SELECT max(statistic.period_end) AS period_end
      FROM category_statistics statistic
      CROSS JOIN config
     WHERE statistic.calculation_version = config.trend_version
       AND statistic.dimension_type = 'category'
       AND statistic.opportunity_score IS NOT NULL
), category_candidates AS (
    SELECT statistic.*
      FROM category_statistics statistic
      CROSS JOIN config
      CROSS JOIN latest_period
     WHERE statistic.calculation_version = config.trend_version
       AND statistic.period_end = latest_period.period_end
       AND statistic.dimension_type = 'category'
       AND statistic.category_slug IS NOT NULL
       AND statistic.opportunity_score >= config.minimum_score
), evidenced AS (
    SELECT
        candidate.*,
        config.recommendation_model,
        config.prompt_version,
        jsonb_build_object(
            'input_scope', jsonb_build_object(
                'level', 'aggregated',
                'contains_individual_videos', false,
                'period_start', candidate.period_start,
                'period_end', candidate.period_end,
                'platform', candidate.platform,
                'region', candidate.region,
                'language', candidate.language
            ),
            'category_statistics', jsonb_build_object(
                'category', candidate.category_slug,
                'sample_size', candidate.sample_size,
                'previous_sample_size', candidate.previous_sample_size,
                'median_views', candidate.median_views,
                'p75_views', candidate.p75_views,
                'p90_views', candidate.p90_views,
                'median_engagement_rate', candidate.median_engagement,
                'median_view_velocity', candidate.median_velocity,
                'median_virality_score', candidate.median_virality,
                'median_monetization_score', candidate.median_monetization,
                'consistency_score', candidate.consistency_score,
                'opportunity_score', candidate.opportunity_score,
                'opportunity_rank', candidate.opportunity_rank,
                'opportunity_percentile', candidate.opportunity_percentile,
                'outlier_rate', candidate.outlier_rate,
                'high_performance_rate', candidate.high_performance_rate,
                'trend_change', candidate.trend_change,
                'trend_direction', candidate.trend_direction
            ),
            'category_format_source_patterns', COALESCE((
                SELECT jsonb_agg(to_jsonb(pattern) ORDER BY pattern.opportunity_score DESC NULLS LAST, pattern.sample_size DESC)
                  FROM (
                      SELECT related.format, related.source_type, related.sample_size,
                             related.median_virality, related.median_monetization,
                             related.consistency_score, related.opportunity_score,
                             related.outlier_rate, related.trend_direction
                        FROM category_statistics related
                       WHERE related.period_start = candidate.period_start
                         AND related.period_end = candidate.period_end
                         AND related.platform = candidate.platform
                         AND related.region IS NOT DISTINCT FROM candidate.region
                         AND related.language IS NOT DISTINCT FROM candidate.language
                         AND related.calculation_version = candidate.calculation_version
                         AND related.dimension_type = 'category_format_source'
                         AND related.category_slug = candidate.category_slug
                       ORDER BY related.opportunity_score DESC NULLS LAST, related.sample_size DESC
                       LIMIT config.context_limit
                  ) pattern
            ), '[]'::JSONB),
            'context_top_formats', COALESCE((
                SELECT jsonb_agg(to_jsonb(format_statistic) ORDER BY format_statistic.opportunity_score DESC NULLS LAST, format_statistic.sample_size DESC)
                  FROM (
                      SELECT related.dimension_value AS format, related.sample_size,
                             related.median_virality, related.median_monetization,
                             related.consistency_score, related.opportunity_score,
                             related.outlier_rate, related.trend_direction
                        FROM category_statistics related
                       WHERE related.period_start = candidate.period_start
                         AND related.period_end = candidate.period_end
                         AND related.platform = candidate.platform
                         AND related.region IS NOT DISTINCT FROM candidate.region
                         AND related.language IS NOT DISTINCT FROM candidate.language
                         AND related.calculation_version = candidate.calculation_version
                         AND related.dimension_type = 'format'
                       ORDER BY related.opportunity_score DESC NULLS LAST, related.sample_size DESC
                       LIMIT config.context_limit
                  ) format_statistic
            ), '[]'::JSONB),
            'context_top_hooks', COALESCE((
                SELECT jsonb_agg(to_jsonb(hook_statistic) ORDER BY hook_statistic.opportunity_score DESC NULLS LAST, hook_statistic.sample_size DESC)
                  FROM (
                      SELECT related.dimension_value AS hook_type, related.sample_size,
                             related.median_virality, related.median_monetization,
                             related.consistency_score, related.opportunity_score,
                             related.outlier_rate, related.trend_direction
                        FROM category_statistics related
                       WHERE related.period_start = candidate.period_start
                         AND related.period_end = candidate.period_end
                         AND related.platform = candidate.platform
                         AND related.region IS NOT DISTINCT FROM candidate.region
                         AND related.language IS NOT DISTINCT FROM candidate.language
                         AND related.calculation_version = candidate.calculation_version
                         AND related.dimension_type = 'hook_type'
                       ORDER BY related.opportunity_score DESC NULLS LAST, related.sample_size DESC
                       LIMIT config.context_limit
                  ) hook_statistic
            ), '[]'::JSONB)
        ) AS evidence_json
      FROM category_candidates candidate
      CROSS JOIN config
), hashed AS (
    SELECT evidenced.*, md5(evidenced.evidence_json::TEXT) AS evidence_hash
      FROM evidenced
), pending AS (
    SELECT hashed.*
      FROM hashed
     WHERE NOT EXISTS (
         SELECT 1
           FROM recommendations recommendation
          WHERE recommendation.category = hashed.category_slug
            AND recommendation.period_start = hashed.period_start
            AND recommendation.period_end = hashed.period_end
            AND recommendation.platform = hashed.platform
            AND recommendation.region IS NOT DISTINCT FROM hashed.region
            AND recommendation.language IS NOT DISTINCT FROM hashed.language
            AND recommendation.prompt_version = hashed.prompt_version
            AND recommendation.model = hashed.recommendation_model
            AND recommendation.evidence_hash = hashed.evidence_hash
     )
)
SELECT
    pending.category_slug,
    pending.period_start,
    pending.period_end,
    pending.platform,
    pending.region,
    pending.language,
    pending.opportunity_score,
    pending.median_virality,
    pending.median_monetization,
    pending.consistency_score,
    pending.calculation_version,
    pending.opportunity_calculation_version,
    pending.recommendation_model,
    pending.prompt_version,
    pending.evidence_json,
    pending.evidence_hash
 FROM pending
 ORDER BY pending.opportunity_score DESC, pending.opportunity_rank, pending.category_slug
 LIMIT (SELECT max_categories FROM config);
$$;

CREATE OR REPLACE FUNCTION build_trendlens_report(
    p_generated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
)
RETURNS TABLE (
    period_start TIMESTAMPTZ,
    period_end TIMESTAMPTZ,
    platform TEXT,
    region CHAR(2),
    language VARCHAR(16),
    generated_at TIMESTAMPTZ,
    report_version TEXT,
    source_calculation_version TEXT,
    source_opportunity_version TEXT,
    recommendation_prompt_version TEXT,
    videos_analyzed INTEGER,
    categories_analyzed INTEGER,
    top_opportunities_count INTEGER,
    viral_but_risky_count INTEGER,
    emerging_trends_count INTEGER,
    report_json JSONB,
    report_markdown TEXT,
    source_hash TEXT
)
LANGUAGE sql
STABLE
AS $$
WITH config AS (
    SELECT
        'youtube'::TEXT AS platform,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'REGION'), ''), 'BR')::CHAR(2) AS region,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'LANGUAGE'), ''), 'pt')::VARCHAR(16) AS language,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'REPORT_VERSION'), ''), 'v2') AS report_version,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'TREND_CALCULATION_VERSION'), ''), 'v1') AS trend_version,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'OPPORTUNITY_CALCULATION_VERSION'), ''), 'v1') AS opportunity_version,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'RECOMMENDATION_PROMPT_VERSION'), ''), 'v2') AS recommendation_prompt_version,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'REPORT_TIMEZONE'), ''), 'America/Sao_Paulo') AS report_timezone,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'REPORT_PERIOD'), '')::INTERVAL, INTERVAL '7 days') AS report_period,
        GREATEST(1, LEAST(20, COALESCE((SELECT (value #>> '{}')::INTEGER FROM settings WHERE key = 'REPORT_TOP_OPPORTUNITIES_LIMIT'), 5))) AS top_limit,
        GREATEST(1, LEAST(20, COALESCE((SELECT (value #>> '{}')::INTEGER FROM settings WHERE key = 'REPORT_VIRAL_RISK_LIMIT'), 5))) AS viral_risk_limit,
        GREATEST(1, LEAST(20, COALESCE((SELECT (value #>> '{}')::INTEGER FROM settings WHERE key = 'REPORT_EMERGING_TRENDS_LIMIT'), 5))) AS emerging_limit,
        GREATEST(0::NUMERIC, LEAST(10::NUMERIC, COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'REPORT_VIRALITY_RISK_MIN'), 6))) AS virality_risk_min,
        GREATEST(0::NUMERIC, LEAST(10::NUMERIC, COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'REPORT_MONETIZATION_RISK_MAX'), 5))) AS monetization_risk_max
), selected_context AS (
    SELECT
        config.platform,
        config.region,
        COALESCE((
            SELECT statistic.language
              FROM category_statistics statistic
             WHERE statistic.platform = config.platform
               AND statistic.region IS NOT DISTINCT FROM config.region
               AND statistic.calculation_version = config.trend_version
               AND statistic.dimension_type = 'category'
               AND statistic.opportunity_score IS NOT NULL
               AND statistic.opportunity_calculation_version = config.opportunity_version
               AND (
                   statistic.language = config.language
                   OR statistic.language LIKE config.language || '-%'
               )
             GROUP BY statistic.language
             ORDER BY
                 (statistic.language = config.language) DESC,
                 count(*) DESC,
                 sum(statistic.sample_size) DESC,
                 statistic.language
             LIMIT 1
        ), config.language)::VARCHAR(16) AS language,
        config.language AS requested_language
      FROM config
), latest_period AS (
    SELECT max(statistic.period_end) AS period_end
      FROM category_statistics statistic
      CROSS JOIN config
      CROSS JOIN selected_context
     WHERE statistic.platform = selected_context.platform
       AND statistic.region IS NOT DISTINCT FROM selected_context.region
       AND statistic.language IS NOT DISTINCT FROM selected_context.language
       AND statistic.calculation_version = config.trend_version
       AND statistic.dimension_type = 'category'
       AND statistic.opportunity_score IS NOT NULL
       AND statistic.opportunity_calculation_version = config.opportunity_version
), bounds AS (
    SELECT
        COALESCE((
            SELECT max(statistic.period_start)
              FROM category_statistics statistic
             WHERE statistic.period_end = latest_period.period_end
               AND statistic.platform = selected_context.platform
               AND statistic.region IS NOT DISTINCT FROM selected_context.region
               AND statistic.language IS NOT DISTINCT FROM selected_context.language
               AND statistic.calculation_version = config.trend_version
               AND statistic.dimension_type = 'category'
        ), p_generated_at - config.report_period) AS period_start,
        COALESCE(latest_period.period_end, p_generated_at) AS period_end
      FROM config
      CROSS JOIN selected_context
      CROSS JOIN latest_period
), base AS (
    SELECT
        statistic.*,
        recommendation.id AS recommendation_id,
        recommendation.summary AS recommendation_summary,
        recommendation.recommended_formats,
        recommendation.recommended_hooks,
        recommendation.risks AS recommendation_risks,
        recommendation.monetization_notes,
        recommendation.model AS recommendation_model,
        recommendation.prompt_version AS used_prompt_version,
        recommendation.generated_at AS recommendation_generated_at
      FROM category_statistics statistic
      CROSS JOIN config
      CROSS JOIN selected_context
      CROSS JOIN latest_period
      LEFT JOIN LATERAL (
          SELECT candidate.*
            FROM recommendations candidate
           WHERE candidate.category = statistic.category_slug
             AND candidate.period_start = statistic.period_start
             AND candidate.period_end = statistic.period_end
             AND candidate.platform = statistic.platform
             AND candidate.region IS NOT DISTINCT FROM statistic.region
             AND candidate.language IS NOT DISTINCT FROM statistic.language
             AND candidate.source_calculation_version = statistic.calculation_version
             AND candidate.source_opportunity_version = statistic.opportunity_calculation_version
             AND candidate.prompt_version = config.recommendation_prompt_version
           ORDER BY candidate.generated_at DESC, candidate.id DESC
           LIMIT 1
      ) recommendation ON TRUE
     WHERE latest_period.period_end IS NOT NULL
       AND statistic.period_end = latest_period.period_end
       AND statistic.platform = selected_context.platform
       AND statistic.region IS NOT DISTINCT FROM selected_context.region
       AND statistic.language IS NOT DISTINCT FROM selected_context.language
       AND statistic.calculation_version = config.trend_version
       AND statistic.dimension_type = 'category'
), coverage AS (
    SELECT
        COALESCE(sum(base.sample_size), 0)::INTEGER AS videos_analyzed,
        count(base.id)::INTEGER AS categories_analyzed,
        count(base.id) FILTER (WHERE base.opportunity_score IS NOT NULL)::INTEGER AS categories_with_opportunity,
        count(base.id) FILTER (WHERE base.recommendation_id IS NOT NULL)::INTEGER AS recommendations_available,
        count(base.id) FILTER (WHERE base.used_prompt_version = config.recommendation_prompt_version)::INTEGER AS current_prompt_recommendations
      FROM config
      LEFT JOIN base ON TRUE
), opportunity_ranked AS (
    SELECT
        base.*,
        row_number() OVER (
            ORDER BY base.opportunity_score DESC, base.opportunity_rank, base.category_slug
        )::INTEGER AS display_rank
      FROM base
     WHERE base.opportunity_score IS NOT NULL
), top_rows AS (
    SELECT opportunity_ranked.*
      FROM opportunity_ranked
      CROSS JOIN config
     WHERE opportunity_ranked.display_rank <= config.top_limit
), risky_ranked AS (
    SELECT
        base.*,
        round(base.median_virality - base.median_monetization, 4) AS risk_gap,
        row_number() OVER (
            ORDER BY
                (base.median_virality - base.median_monetization) DESC,
                base.median_virality DESC,
                base.category_slug
        )::INTEGER AS display_rank
      FROM base
      CROSS JOIN config
     WHERE base.median_virality >= config.virality_risk_min
       AND base.median_monetization <= config.monetization_risk_max
), risky_rows AS (
    SELECT risky_ranked.*
      FROM risky_ranked
      CROSS JOIN config
     WHERE risky_ranked.display_rank <= config.viral_risk_limit
), emerging_ranked AS (
    SELECT
        base.*,
        row_number() OVER (
            ORDER BY base.trend_change DESC NULLS LAST, base.opportunity_score DESC, base.category_slug
        )::INTEGER AS display_rank
      FROM base
     WHERE base.trend_direction = 'rising'
), emerging_rows AS (
    SELECT emerging_ranked.*
      FROM emerging_ranked
      CROSS JOIN config
     WHERE emerging_ranked.display_rank <= config.emerging_limit
), top_section AS (
    SELECT
        COALESCE(jsonb_agg(
            jsonb_build_object(
                'rank', top_rows.display_rank,
                'category', top_rows.category_slug,
                'opportunity_score', top_rows.opportunity_score,
                'virality_score', top_rows.median_virality,
                'monetization_score', top_rows.median_monetization,
                'consistency_score', top_rows.consistency_score,
                'evidence', jsonb_build_object(
                    'sample_size', top_rows.sample_size,
                    'previous_sample_size', top_rows.previous_sample_size,
                    'median_views', top_rows.median_views,
                    'p75_views', top_rows.p75_views,
                    'p90_views', top_rows.p90_views,
                    'median_engagement_rate', top_rows.median_engagement,
                    'median_view_velocity', top_rows.median_velocity,
                    'outlier_rate', top_rows.outlier_rate,
                    'high_performance_rate', top_rows.high_performance_rate,
                    'trend_direction', top_rows.trend_direction,
                    'trend_change', top_rows.trend_change
                ),
                'recommendation', CASE
                    WHEN top_rows.recommendation_id IS NULL THEN NULL
                    ELSE jsonb_build_object(
                        'summary', top_rows.recommendation_summary,
                        'recommended_formats', top_rows.recommended_formats,
                        'recommended_hooks', top_rows.recommended_hooks,
                        'risks', top_rows.recommendation_risks,
                        'monetization_notes', top_rows.monetization_notes,
                        'model', top_rows.recommendation_model,
                        'prompt_version', top_rows.used_prompt_version,
                        'is_current_prompt', top_rows.used_prompt_version = config.recommendation_prompt_version
                    )
                END
            )
            ORDER BY top_rows.display_rank
        ) FILTER (WHERE top_rows.category_slug IS NOT NULL), '[]'::JSONB) AS items,
        count(top_rows.category_slug)::INTEGER AS item_count
      FROM config
      LEFT JOIN top_rows ON TRUE
), risky_section AS (
    SELECT
        COALESCE(jsonb_agg(
            jsonb_build_object(
                'rank', risky_rows.display_rank,
                'category', risky_rows.category_slug,
                'virality_score', risky_rows.median_virality,
                'monetization_score', risky_rows.median_monetization,
                'risk_gap', risky_rows.risk_gap,
                'sample_size', risky_rows.sample_size,
                'outlier_rate', risky_rows.outlier_rate,
                'risks', COALESCE(to_jsonb(risky_rows.recommendation_risks), '[]'::JSONB)
            )
            ORDER BY risky_rows.display_rank
        ) FILTER (WHERE risky_rows.category_slug IS NOT NULL), '[]'::JSONB) AS items,
        count(risky_rows.category_slug)::INTEGER AS item_count
      FROM risky_rows
      RIGHT JOIN config ON TRUE
), emerging_section AS (
    SELECT
        COALESCE(jsonb_agg(
            jsonb_build_object(
                'rank', emerging_rows.display_rank,
                'category', emerging_rows.category_slug,
                'trend_direction', emerging_rows.trend_direction,
                'trend_change', emerging_rows.trend_change,
                'sample_size', emerging_rows.sample_size,
                'previous_sample_size', emerging_rows.previous_sample_size,
                'opportunity_score', emerging_rows.opportunity_score,
                'virality_score', emerging_rows.median_virality
            )
            ORDER BY emerging_rows.display_rank
        ) FILTER (WHERE emerging_rows.category_slug IS NOT NULL), '[]'::JSONB) AS items,
        count(emerging_rows.category_slug)::INTEGER AS item_count
      FROM emerging_rows
      RIGHT JOIN config ON TRUE
), top_markdown AS (
    SELECT COALESCE(string_agg(
        format(
            E'### %s. %s\n\n- Opportunity Score: %s/10\n- Virality Score: %s/10\n- Monetization Score: %s/10\n- Consistency Score: %s/10\n- Amostra: %s %s\n- Mediana de views: %s\n- Outlier rate: %s\n- Tendência: %s',
            top_rows.display_rank,
            initcap(replace(top_rows.category_slug, '_', ' ')),
            round(top_rows.opportunity_score, 2),
            round(top_rows.median_virality, 2),
            round(top_rows.median_monetization, 2),
            round(top_rows.consistency_score, 2),
            top_rows.sample_size,
            CASE WHEN top_rows.sample_size = 1 THEN 'vídeo' ELSE 'vídeos' END,
            COALESCE(round(top_rows.median_views, 0)::TEXT, 'indisponível'),
            COALESCE(round(top_rows.outlier_rate * 100, 2)::TEXT || '%', 'indisponível'),
            top_rows.trend_direction
        ) || CASE
            WHEN top_rows.recommendation_id IS NULL THEN E'\n\n_Recomendação estruturada ainda não disponível para este contexto._'
            ELSE format(
                E'\n\n**Recomendação (%s%s)**\n\n%s\n\n**Formatos sugeridos**\n%s\n\n**Hooks sugeridos**\n%s\n\n**Riscos**\n%s\n\n**Observações de monetização**\n%s',
                top_rows.used_prompt_version,
                CASE WHEN top_rows.used_prompt_version = config.recommendation_prompt_version THEN '' ELSE ', histórico' END,
                regexp_replace(top_rows.recommendation_summary, E'[\r\n]+', ' ', 'g'),
                COALESCE((SELECT string_agg('- ' || regexp_replace(item, E'[\r\n]+', ' ', 'g'), E'\n') FROM unnest(top_rows.recommended_formats) item), '- Não disponível'),
                COALESCE((SELECT string_agg('- ' || regexp_replace(item, E'[\r\n]+', ' ', 'g'), E'\n') FROM unnest(top_rows.recommended_hooks) item), '- Não disponível'),
                COALESCE((SELECT string_agg('- ' || regexp_replace(item, E'[\r\n]+', ' ', 'g'), E'\n') FROM unnest(top_rows.recommendation_risks) item), '- Não disponível'),
                COALESCE((SELECT string_agg('- ' || regexp_replace(item, E'[\r\n]+', ' ', 'g'), E'\n') FROM unnest(top_rows.monetization_notes) item), '- Não disponível')
            )
        END,
        E'\n\n'
        ORDER BY top_rows.display_rank
    ) FILTER (WHERE top_rows.category_slug IS NOT NULL), '_Nenhuma categoria com Opportunity Score está disponível neste contexto._') AS body
      FROM config
      LEFT JOIN top_rows ON TRUE
), risky_markdown AS (
    SELECT COALESCE(string_agg(
        format(
            E'### %s. %s\n\n- Virality Score: %s/10\n- Monetization Score: %s/10\n- Diferença de risco: %s pontos\n- Amostra: %s %s\n- Outlier rate: %s',
            risky_rows.display_rank,
            initcap(replace(risky_rows.category_slug, '_', ' ')),
            round(risky_rows.median_virality, 2),
            round(risky_rows.median_monetization, 2),
            risky_rows.risk_gap,
            risky_rows.sample_size,
            CASE WHEN risky_rows.sample_size = 1 THEN 'vídeo' ELSE 'vídeos' END,
            COALESCE(round(risky_rows.outlier_rate * 100, 2)::TEXT || '%', 'indisponível')
        ),
        E'\n\n'
        ORDER BY risky_rows.display_rank
    ) FILTER (WHERE risky_rows.category_slug IS NOT NULL), '_Nenhuma categoria atingiu simultaneamente os limites configurados de alta viralidade e baixa monetização._') AS body
      FROM config
      LEFT JOIN risky_rows ON TRUE
), emerging_markdown AS (
    SELECT COALESCE(string_agg(
        format(
            E'### %s. %s\n\n- Direção: rising\n- Variação da mediana de Virality Score: %s%%\n- Amostra atual: %s %s\n- Amostra anterior: %s %s\n- Opportunity Score: %s/10',
            emerging_rows.display_rank,
            initcap(replace(emerging_rows.category_slug, '_', ' ')),
            COALESCE(round(emerging_rows.trend_change * 100, 2)::TEXT, 'indisponível'),
            emerging_rows.sample_size,
            CASE WHEN emerging_rows.sample_size = 1 THEN 'vídeo' ELSE 'vídeos' END,
            emerging_rows.previous_sample_size,
            CASE WHEN emerging_rows.previous_sample_size = 1 THEN 'vídeo' ELSE 'vídeos' END,
            round(emerging_rows.opportunity_score, 2)
        ),
        E'\n\n'
        ORDER BY emerging_rows.display_rank
    ) FILTER (WHERE emerging_rows.category_slug IS NOT NULL), '_Nenhuma tendência emergente possui amostra suficiente no período atual._') AS body
      FROM config
      LEFT JOIN emerging_rows ON TRUE
), source_payload AS (
    SELECT jsonb_build_object(
        'schema_version', '1.0',
        'title', 'TrendLens — Relatório Semanal',
        'report_version', config.report_version,
        'period', jsonb_build_object(
            'start', bounds.period_start,
            'end', bounds.period_end,
            'timezone', config.report_timezone
        ),
        'context', jsonb_build_object(
            'platform', selected_context.platform,
            'region', selected_context.region,
            'language', selected_context.language,
            'requested_language', selected_context.requested_language
        ),
        'coverage', jsonb_build_object(
            'videos_analyzed', coverage.videos_analyzed,
            'categories_analyzed', coverage.categories_analyzed,
            'categories_with_opportunity', coverage.categories_with_opportunity,
            'recommendations_available', coverage.recommendations_available,
            'current_prompt_recommendations', coverage.current_prompt_recommendations
        ),
        'source_versions', jsonb_build_object(
            'trend', config.trend_version,
            'opportunity', config.opportunity_version,
            'recommendation_prompt', config.recommendation_prompt_version
        ),
        'top_opportunities', top_section.items,
        'viral_but_risky', risky_section.items,
        'emerging_trends', emerging_section.items,
        'methodology', jsonb_build_object(
            'viral_but_risky', jsonb_build_object(
                'minimum_virality_score', config.virality_risk_min,
                'maximum_monetization_score', config.monetization_risk_max
            ),
            'quantitative_source', 'postgresql',
            'recommendation_policy', 'patterns_not_individual_videos'
        ),
        'notices', jsonb_build_array(
            'Todos os valores quantitativos foram calculados no PostgreSQL.',
            'Scores são índices heurísticos relativos à amostra e não garantem viralização ou receita.',
            'Tendências rising exigem amostra mínima nas janelas atual e anterior.'
        )
    ) AS value
      FROM config
      CROSS JOIN selected_context
      CROSS JOIN bounds
      CROSS JOIN coverage
      CROSS JOIN top_section
      CROSS JOIN risky_section
      CROSS JOIN emerging_section
), rendered AS (
    SELECT
        source_payload.value || jsonb_build_object('generated_at', p_generated_at) AS report_json,
        format(
            E'# TrendLens — Relatório Semanal\n\n_Gerado em %s (%s)_\n\n## Escopo\n\n- Período: %s → %s\n- Plataforma: %s\n- Região: %s\n- Idioma: %s\n- Vídeos analisados: %s\n- Categorias analisadas: %s\n- Recomendações disponíveis: %s (%s no prompt atual)\n\n## Top Opportunities\n\n%s\n\n## Viral but Risky\n\n%s\n\n## Tendências emergentes\n\n%s\n\n## Notas metodológicas\n\n- Todos os valores quantitativos foram calculados no PostgreSQL.\n- Scores são índices heurísticos relativos à amostra e não garantem viralização ou receita.\n- Recomendações descrevem padrões e não vídeos individuais.\n\n_Versão do relatório: %s_',
            to_char(timezone(config.report_timezone, p_generated_at), 'DD/MM/YYYY HH24:MI'),
            config.report_timezone,
            to_char(timezone(config.report_timezone, bounds.period_start), 'DD/MM/YYYY HH24:MI'),
            to_char(timezone(config.report_timezone, bounds.period_end), 'DD/MM/YYYY HH24:MI'),
            selected_context.platform,
            selected_context.region,
            selected_context.language,
            coverage.videos_analyzed,
            coverage.categories_analyzed,
            coverage.recommendations_available,
            coverage.current_prompt_recommendations,
            top_markdown.body,
            risky_markdown.body,
            emerging_markdown.body,
            config.report_version
        ) AS report_markdown,
        md5(source_payload.value::TEXT) AS source_hash
      FROM config
      CROSS JOIN selected_context
      CROSS JOIN bounds
      CROSS JOIN coverage
      CROSS JOIN top_markdown
      CROSS JOIN risky_markdown
      CROSS JOIN emerging_markdown
      CROSS JOIN source_payload
)
SELECT
    bounds.period_start,
    bounds.period_end,
    selected_context.platform,
    selected_context.region,
    selected_context.language,
    p_generated_at,
    config.report_version,
    config.trend_version,
    config.opportunity_version,
    config.recommendation_prompt_version,
    coverage.videos_analyzed,
    coverage.categories_analyzed,
    top_section.item_count,
    risky_section.item_count,
    emerging_section.item_count,
    rendered.report_json,
    rendered.report_markdown,
    rendered.source_hash
  FROM config
  CROSS JOIN selected_context
  CROSS JOIN bounds
  CROSS JOIN coverage
  CROSS JOIN top_section
  CROSS JOIN risky_section
  CROSS JOIN emerging_section
  CROSS JOIN rendered;
$$;

CREATE TABLE IF NOT EXISTS pipeline_observability_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_start TIMESTAMPTZ NOT NULL,
    period_end TIMESTAMPTZ NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observability_version TEXT NOT NULL,
    overall_status TEXT NOT NULL,
    workflow_count INTEGER NOT NULL,
    run_count INTEGER NOT NULL,
    error_count INTEGER NOT NULL,
    retry_count INTEGER NOT NULL,
    report_json JSONB NOT NULL,
    source_hash TEXT NOT NULL,
    CONSTRAINT pipeline_observability_period_check
        CHECK (period_end > period_start),
    CONSTRAINT pipeline_observability_version_check
        CHECK (length(btrim(observability_version)) > 0),
    CONSTRAINT pipeline_observability_status_check
        CHECK (overall_status IN ('healthy', 'degraded', 'critical')),
    CONSTRAINT pipeline_observability_counts_check
        CHECK (
            workflow_count >= 0
            AND run_count >= 0
            AND error_count >= 0
            AND retry_count >= 0
        ),
    CONSTRAINT pipeline_observability_json_check
        CHECK (
            jsonb_typeof(report_json) = 'object'
            AND report_json ? 'summary'
            AND report_json ? 'pipeline_metrics'
            AND report_json ? 'workflow_health'
            AND report_json ? 'recent_errors'
        ),
    CONSTRAINT pipeline_observability_source_hash_check
        CHECK (source_hash ~ '^[a-f0-9]{32}$')
);

CREATE OR REPLACE FUNCTION build_pipeline_observability(
    p_generated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
)
RETURNS TABLE (
    period_start TIMESTAMPTZ,
    period_end TIMESTAMPTZ,
    generated_at TIMESTAMPTZ,
    observability_version TEXT,
    overall_status TEXT,
    workflow_count INTEGER,
    run_count INTEGER,
    error_count INTEGER,
    retry_count INTEGER,
    report_json JSONB,
    source_hash TEXT
)
LANGUAGE sql
STABLE
AS $$
WITH config AS (
    SELECT
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'OBSERVABILITY_VERSION'), ''), 'v1') AS observability_version,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'OBSERVABILITY_TIMEZONE'), ''), 'America/Sao_Paulo') AS report_timezone,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'OBSERVABILITY_PERIOD'), '')::INTERVAL, INTERVAL '24 hours') AS report_period,
        GREATEST(1, COALESCE((SELECT (value #>> '{}')::INTEGER FROM settings WHERE key = 'OBSERVABILITY_STALE_RUN_MINUTES'), 120)) AS stale_run_minutes,
        GREATEST(0::NUMERIC, LEAST(10::NUMERIC, COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'OBSERVABILITY_HIGH_VIRALITY_THRESHOLD'), 7))) AS high_virality_threshold,
        GREATEST(0::NUMERIC, LEAST(10::NUMERIC, COALESCE((SELECT (value #>> '{}')::NUMERIC FROM settings WHERE key = 'OBSERVABILITY_HIGH_OPPORTUNITY_THRESHOLD'), 7))) AS high_opportunity_threshold,
        GREATEST(1, LEAST(100, COALESCE((SELECT (value #>> '{}')::INTEGER FROM settings WHERE key = 'OBSERVABILITY_ERROR_LIMIT'), 20))) AS error_limit,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'METRICS_CALCULATION_VERSION'), ''), 'v1') AS metrics_version,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'TREND_CALCULATION_VERSION'), ''), 'v1') AS trend_version,
        COALESCE(NULLIF((SELECT value #>> '{}' FROM settings WHERE key = 'OPPORTUNITY_CALCULATION_VERSION'), ''), 'v1') AS opportunity_version
), bounds AS (
    SELECT
        date_trunc('hour', p_generated_at) - config.report_period AS period_start,
        date_trunc('hour', p_generated_at) AS period_end
      FROM config
), expected_workflows AS (
    SELECT *
      FROM (VALUES
        (1, '01 - TrendLens - YouTube Data Collector', 'collection'),
        (2, '02 - TrendLens - Video Snapshot Tracker', 'snapshots'),
        (3, '03 - TrendLens - AI Content Classifier', 'classification'),
        (4, '04 - TrendLens - Metrics Engine & Virality Score', 'metrics'),
        (5, '05 - TrendLens - Trend Engine', 'trends'),
        (6, '06 - TrendLens - Monetization Engine', 'monetization'),
        (7, '07 - TrendLens - Opportunity Engine', 'opportunities'),
        (8, '08 - TrendLens - Recommendation AI', 'recommendations'),
        (9, '09 - TrendLens - Report', 'reporting')
      ) AS workflow(sort_order, workflow, stage)
), period_runs AS MATERIALIZED (
    SELECT run.*
      FROM pipeline_runs run
      CROSS JOIN bounds
     WHERE run.started_at >= bounds.period_start
       AND run.started_at < bounds.period_end
       AND run.workflow IN (SELECT workflow FROM expected_workflows)
), period_errors AS MATERIALIZED (
    SELECT error.*
      FROM pipeline_errors error
      CROSS JOIN bounds
     WHERE error.occurred_at >= bounds.period_start
       AND error.occurred_at < bounds.period_end
       AND error.workflow IN (SELECT workflow FROM expected_workflows)
), run_stats AS (
    SELECT
        expected.sort_order,
        expected.workflow,
        expected.stage,
        count(run.id)::INTEGER AS run_count,
        count(run.id) FILTER (WHERE run.status = 'success')::INTEGER AS success_count,
        count(run.id) FILTER (WHERE run.status = 'partial')::INTEGER AS partial_count,
        count(run.id) FILTER (WHERE run.status = 'failed')::INTEGER AS failed_count,
        count(run.id) FILTER (WHERE run.status = 'running')::INTEGER AS running_count,
        COALESCE(sum(run.items_received), 0)::BIGINT AS items_received,
        COALESCE(sum(run.items_processed), 0)::BIGINT AS items_processed,
        COALESCE(sum(run.items_skipped), 0)::BIGINT AS items_skipped,
        COALESCE(sum(run.items_failed), 0)::BIGINT AS items_failed,
        COALESCE(sum(run.api_calls), 0)::BIGINT AS api_calls,
        COALESCE(sum(run.quota_units_estimated), 0)::BIGINT AS quota_units_estimated,
        round(avg(run.duration_seconds) FILTER (WHERE run.duration_seconds IS NOT NULL), 3) AS average_duration_seconds,
        round(percentile_cont(0.95) WITHIN GROUP (ORDER BY run.duration_seconds) FILTER (WHERE run.duration_seconds IS NOT NULL)::NUMERIC, 3) AS p95_duration_seconds
      FROM expected_workflows expected
      LEFT JOIN period_runs run ON run.workflow = expected.workflow
     GROUP BY expected.sort_order, expected.workflow, expected.stage
), error_stats AS (
    SELECT
        expected.workflow,
        count(error.id)::INTEGER AS error_events,
        COALESCE(sum(error.retry_count), 0)::INTEGER AS retry_count
      FROM expected_workflows expected
      LEFT JOIN period_errors error ON error.workflow = expected.workflow
     GROUP BY expected.workflow
), stale_stats AS (
    SELECT
        expected.workflow,
        count(run.id)::INTEGER AS stale_running_count
      FROM expected_workflows expected
      CROSS JOIN config
      CROSS JOIN bounds
      LEFT JOIN pipeline_runs run
        ON run.workflow = expected.workflow
       AND run.status = 'running'
       AND run.started_at < bounds.period_end - make_interval(mins => config.stale_run_minutes)
     GROUP BY expected.workflow
), latest_runs AS (
    SELECT
        expected.workflow,
        latest.id,
        latest.status,
        latest.started_at,
        latest.finished_at,
        latest.duration_seconds
      FROM expected_workflows expected
      CROSS JOIN bounds
      LEFT JOIN LATERAL (
          SELECT run.id, run.status, run.started_at, run.finished_at, run.duration_seconds
            FROM pipeline_runs run
           WHERE run.workflow = expected.workflow
             AND run.started_at < bounds.period_end
           ORDER BY run.started_at DESC, run.id DESC
           LIMIT 1
      ) latest ON TRUE
), workflow_rows AS (
    SELECT
        stats.*,
        errors.error_events,
        errors.retry_count,
        stale.stale_running_count,
        latest.id AS latest_run_id,
        latest.status AS latest_status,
        latest.started_at AS latest_started_at,
        latest.finished_at AS latest_finished_at,
        latest.duration_seconds AS latest_duration_seconds,
        CASE
            WHEN stale.stale_running_count > 0 OR stats.failed_count > 0 THEN 'critical'
            WHEN stats.partial_count > 0 OR errors.error_events > 0 THEN 'degraded'
            WHEN stats.run_count = 0 THEN 'unknown'
            ELSE 'healthy'
        END AS health_status
      FROM run_stats stats
      JOIN error_stats errors USING (workflow)
      JOIN stale_stats stale USING (workflow)
      JOIN latest_runs latest USING (workflow)
), workflow_section AS (
    SELECT jsonb_agg(
        jsonb_build_object(
            'workflow', workflow,
            'stage', stage,
            'health_status', health_status,
            'runs', jsonb_build_object(
                'total', run_count,
                'success', success_count,
                'partial', partial_count,
                'failed', failed_count,
                'running', running_count,
                'stale_running', stale_running_count
            ),
            'counters', jsonb_build_object(
                'items_received', items_received,
                'items_processed', items_processed,
                'items_skipped', items_skipped,
                'items_failed', items_failed,
                'api_calls', api_calls,
                'quota_units_estimated', quota_units_estimated,
                'error_events', error_events,
                'retries', retry_count
            ),
            'duration_seconds', jsonb_build_object(
                'average', average_duration_seconds,
                'p95', p95_duration_seconds
            ),
            'latest_run', CASE
                WHEN latest_run_id IS NULL THEN NULL
                ELSE jsonb_build_object(
                    'id', latest_run_id,
                    'status', latest_status,
                    'started_at', latest_started_at,
                    'finished_at', latest_finished_at,
                    'duration_seconds', latest_duration_seconds
                )
            END
        ) ORDER BY sort_order
    ) AS items
      FROM workflow_rows
), summary AS (
    SELECT
        count(*)::INTEGER AS workflow_count,
        COALESCE(sum(run_count), 0)::INTEGER AS run_count,
        COALESCE(sum(success_count), 0)::INTEGER AS success_count,
        COALESCE(sum(partial_count), 0)::INTEGER AS partial_count,
        COALESCE(sum(failed_count), 0)::INTEGER AS failed_count,
        COALESCE(sum(running_count), 0)::INTEGER AS running_count,
        COALESCE(sum(items_failed), 0)::BIGINT AS items_failed,
        COALESCE(sum(error_events), 0)::INTEGER AS error_count,
        COALESCE(sum(retry_count), 0)::INTEGER AS retry_count,
        count(*) FILTER (WHERE health_status = 'healthy')::INTEGER AS healthy_workflows,
        count(*) FILTER (WHERE health_status = 'degraded')::INTEGER AS degraded_workflows,
        count(*) FILTER (WHERE health_status = 'critical')::INTEGER AS critical_workflows,
        count(*) FILTER (WHERE health_status = 'unknown')::INTEGER AS unknown_workflows,
        CASE
            WHEN count(*) FILTER (WHERE health_status = 'critical') > 0 THEN 'critical'
            WHEN count(*) FILTER (WHERE health_status = 'degraded') > 0 THEN 'degraded'
            ELSE 'healthy'
        END AS overall_status
      FROM workflow_rows
), scalar_metrics AS (
    SELECT
        COALESCE(sum(run.items_processed) FILTER (WHERE run.workflow = '01 - TrendLens - YouTube Data Collector'), 0)::BIGINT AS videos_collected,
        COALESCE(sum(CASE WHEN run.workflow = '01 - TrendLens - YouTube Data Collector' THEN COALESCE((run.metadata ->> 'new_videos')::BIGINT, 0) ELSE 0 END), 0)::BIGINT AS new_videos,
        COALESCE(sum(CASE WHEN run.workflow = '01 - TrendLens - YouTube Data Collector' THEN COALESCE((run.metadata ->> 'duplicate_videos')::BIGINT, 0) ELSE 0 END), 0)::BIGINT AS duplicate_videos,
        COALESCE(sum(CASE WHEN run.workflow IN ('01 - TrendLens - YouTube Data Collector', '02 - TrendLens - Video Snapshot Tracker') THEN COALESCE((run.metadata ->> 'snapshots_collected')::BIGINT, 0) ELSE 0 END), 0)::BIGINT AS snapshots_collected,
        COALESCE(sum(run.items_processed) FILTER (WHERE run.workflow = '03 - TrendLens - AI Content Classifier'), 0)::BIGINT AS ai_classifications,
        COALESCE(sum(run.items_failed) FILTER (WHERE run.workflow = '03 - TrendLens - AI Content Classifier'), 0)::BIGINT AS classification_errors,
        round((
            sum(run.duration_seconds) FILTER (
                WHERE run.workflow = '03 - TrendLens - AI Content Classifier'
                  AND run.finished_at IS NOT NULL
            ) / NULLIF(sum(run.items_processed + run.items_failed) FILTER (
                WHERE run.workflow = '03 - TrendLens - AI Content Classifier'
                  AND run.finished_at IS NOT NULL
            ), 0)
        )::NUMERIC, 3) AS average_classification_latency_seconds,
        (SELECT count(*)::INTEGER FROM period_errors error WHERE error.error_type ~ '^(youtube|ai)_') AS api_errors,
        (SELECT COALESCE(sum(error.retry_count), 0)::INTEGER FROM period_errors error) AS retries,
        COALESCE(sum(run.items_failed), 0)::BIGINT AS items_with_error
      FROM period_runs run
), videos_by_category AS (
    SELECT COALESCE(jsonb_agg(
        jsonb_build_object(
            'category', category,
            'videos', videos
        ) ORDER BY videos DESC, category
    ), '[]'::JSONB) AS items
      FROM (
        SELECT COALESCE(category.slug, 'uncategorized') AS category, count(*)::INTEGER AS videos
          FROM video_classifications classification
          LEFT JOIN categories category ON category.id = classification.category_id
          CROSS JOIN bounds
         WHERE classification.classified_at < bounds.period_end
         GROUP BY COALESCE(category.slug, 'uncategorized')
      ) grouped
), high_virality AS (
    SELECT
        count(*)::INTEGER AS total,
        COALESCE(jsonb_agg(
            jsonb_build_object(
                'video_id', ranked.video_id,
                'external_id', ranked.external_id,
                'virality_score', ranked.virality_score,
                'calculated_at', ranked.calculated_at
            ) ORDER BY ranked.virality_score DESC, ranked.video_id
        ) FILTER (WHERE ranked.display_order <= 10), '[]'::JSONB) AS items
      FROM (
        SELECT
            latest.video_id,
            latest.external_id,
            latest.virality_score,
            latest.calculated_at,
            row_number() OVER (ORDER BY latest.virality_score DESC, latest.video_id) AS display_order
          FROM (
            SELECT DISTINCT ON (metric.video_id)
                metric.video_id,
                video.external_id,
                metric.virality_score,
                metric.calculated_at
              FROM video_metrics metric
              JOIN videos video ON video.id = metric.video_id
              CROSS JOIN config
              CROSS JOIN bounds
             WHERE metric.calculation_version = config.metrics_version
               AND metric.calculated_at < bounds.period_end
             ORDER BY metric.video_id, metric.calculated_at DESC, metric.id DESC
          ) latest
          CROSS JOIN config
         WHERE latest.virality_score >= config.high_virality_threshold
      ) ranked
), latest_opportunity_period AS (
    SELECT max(statistic.period_end) AS period_end
      FROM category_statistics statistic
      CROSS JOIN config
      CROSS JOIN bounds
     WHERE statistic.dimension_type = 'category'
       AND statistic.calculation_version = config.trend_version
       AND statistic.opportunity_calculation_version = config.opportunity_version
       AND statistic.opportunity_score IS NOT NULL
       AND statistic.period_end < bounds.period_end
), high_opportunities AS (
    SELECT
        count(*)::INTEGER AS total,
        COALESCE(jsonb_agg(
            jsonb_build_object(
                'category', statistic.category_slug,
                'opportunity_score', statistic.opportunity_score,
                'opportunity_rank', statistic.opportunity_rank,
                'sample_size', statistic.sample_size,
                'period_end', statistic.period_end
            ) ORDER BY statistic.opportunity_score DESC, statistic.category_slug
        ) FILTER (WHERE statistic.category_slug IS NOT NULL), '[]'::JSONB) AS items
      FROM category_statistics statistic
      CROSS JOIN config
      CROSS JOIN latest_opportunity_period latest
     WHERE statistic.dimension_type = 'category'
       AND statistic.calculation_version = config.trend_version
       AND statistic.opportunity_calculation_version = config.opportunity_version
       AND statistic.period_end = latest.period_end
       AND statistic.opportunity_score >= config.high_opportunity_threshold
), recent_errors AS (
    SELECT COALESCE(jsonb_agg(
        jsonb_build_object(
            'id', recent.id,
            'pipeline_run_id', recent.pipeline_run_id,
            'workflow', recent.workflow,
            'node', recent.node,
            'occurred_at', recent.occurred_at,
            'error_type', recent.error_type,
            'external_id', recent.external_id,
            'retry_count', recent.retry_count
        ) ORDER BY recent.occurred_at DESC, recent.id DESC
    ), '[]'::JSONB) AS items
      FROM (
        SELECT
            error.*,
            row_number() OVER (ORDER BY error.occurred_at DESC, error.id DESC) AS error_order
          FROM period_errors error
      ) recent
      CROSS JOIN config
     WHERE recent.error_order <= config.error_limit
), source_payload AS (
    SELECT jsonb_build_object(
        'schema_version', '1.0',
        'observability_version', config.observability_version,
        'period', jsonb_build_object(
            'start', bounds.period_start,
            'end', bounds.period_end,
            'timezone', config.report_timezone,
            'closed_window', true
        ),
        'status', summary.overall_status,
        'summary', jsonb_build_object(
            'workflows', summary.workflow_count,
            'runs', summary.run_count,
            'success', summary.success_count,
            'partial', summary.partial_count,
            'failed', summary.failed_count,
            'running', summary.running_count,
            'items_with_error', summary.items_failed,
            'error_events', summary.error_count,
            'retries', summary.retry_count,
            'healthy_workflows', summary.healthy_workflows,
            'degraded_workflows', summary.degraded_workflows,
            'critical_workflows', summary.critical_workflows,
            'unknown_workflows', summary.unknown_workflows
        ),
        'pipeline_metrics', jsonb_build_object(
            'videos_collected', scalar_metrics.videos_collected,
            'new_videos', scalar_metrics.new_videos,
            'duplicate_videos', scalar_metrics.duplicate_videos,
            'snapshots_collected', scalar_metrics.snapshots_collected,
            'ai_classifications', scalar_metrics.ai_classifications,
            'classification_errors', scalar_metrics.classification_errors,
            'average_classification_latency_seconds', scalar_metrics.average_classification_latency_seconds,
            'api_errors', scalar_metrics.api_errors,
            'retries', scalar_metrics.retries,
            'items_with_error', scalar_metrics.items_with_error,
            'videos_by_category', videos_by_category.items,
            'high_virality_videos', jsonb_build_object(
                'threshold', config.high_virality_threshold,
                'total', high_virality.total,
                'top_items', high_virality.items
            ),
            'high_opportunity_categories', jsonb_build_object(
                'threshold', config.high_opportunity_threshold,
                'total', high_opportunities.total,
                'items', high_opportunities.items
            )
        ),
        'workflow_health', workflow_section.items,
        'recent_errors', recent_errors.items,
        'methodology', jsonb_build_object(
            'run_window', '[start,end)',
            'classification_latency', 'sum_duration_divided_by_processed_plus_failed',
            'retry_scope', 'retries_recorded_on_terminal_errors',
            'error_payload_policy', 'messages_and_metadata_omitted'
        ),
        'notices', jsonb_build_array(
            'A janela termina no início da hora corrente para produzir snapshots idempotentes.',
            'Retries bem-sucedidos dentro de um node não são expostos pelo n8n e não entram no contador.',
            'Eventos recentes omitem error_message e metadata para não expor dados sensíveis.'
        )
    ) AS value
      FROM config
      CROSS JOIN bounds
      CROSS JOIN summary
      CROSS JOIN scalar_metrics
      CROSS JOIN videos_by_category
      CROSS JOIN high_virality
      CROSS JOIN high_opportunities
      CROSS JOIN workflow_section
      CROSS JOIN recent_errors
), rendered AS (
    SELECT
        source_payload.value || jsonb_build_object(
            'generated_at', p_generated_at,
            'source_hash', md5(source_payload.value::TEXT)
        ) AS report_json,
        md5(source_payload.value::TEXT) AS source_hash
      FROM source_payload
)
SELECT
    bounds.period_start,
    bounds.period_end,
    p_generated_at,
    config.observability_version,
    summary.overall_status,
    summary.workflow_count,
    summary.run_count,
    summary.error_count,
    summary.retry_count,
    rendered.report_json,
    rendered.source_hash
  FROM config
  CROSS JOIN bounds
  CROSS JOIN summary
  CROSS JOIN rendered;
$$;


