CREATE TABLE IF NOT EXISTS recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL,
    period_start TIMESTAMPTZ NOT NULL,
    period_end TIMESTAMPTZ NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    opportunity_score NUMERIC(6, 4) NOT NULL,
    virality_score NUMERIC(6, 4) NOT NULL,
    monetization_score NUMERIC(6, 4) NOT NULL,
    summary TEXT NOT NULL,
    recommended_formats TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    recommended_hooks TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    risks TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    monetization_notes TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    evidence_json JSONB NOT NULL,
    model TEXT NOT NULL,
    CONSTRAINT recommendations_period_check
        CHECK (period_end > period_start),
    CONSTRAINT recommendations_opportunity_check
        CHECK (opportunity_score BETWEEN 0 AND 10),
    CONSTRAINT recommendations_virality_check
        CHECK (virality_score BETWEEN 0 AND 10),
    CONSTRAINT recommendations_monetization_check
        CHECK (monetization_score BETWEEN 0 AND 10),
    CONSTRAINT recommendations_evidence_object_check
        CHECK (jsonb_typeof(evidence_json) = 'object')
);

CREATE TABLE IF NOT EXISTS pipeline_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow TEXT NOT NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    status TEXT NOT NULL,
    items_received INTEGER NOT NULL DEFAULT 0,
    items_processed INTEGER NOT NULL DEFAULT 0,
    items_skipped INTEGER NOT NULL DEFAULT 0,
    items_failed INTEGER NOT NULL DEFAULT 0,
    api_calls INTEGER NOT NULL DEFAULT 0,
    quota_units_estimated INTEGER NOT NULL DEFAULT 0,
    duration_seconds NUMERIC(14, 3),
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT pipeline_runs_status_check
        CHECK (status IN ('running', 'success', 'partial', 'failed', 'cancelled')),
    CONSTRAINT pipeline_runs_items_received_check
        CHECK (items_received >= 0),
    CONSTRAINT pipeline_runs_items_processed_check
        CHECK (items_processed >= 0),
    CONSTRAINT pipeline_runs_items_skipped_check
        CHECK (items_skipped >= 0),
    CONSTRAINT pipeline_runs_items_failed_check
        CHECK (items_failed >= 0),
    CONSTRAINT pipeline_runs_api_calls_check
        CHECK (api_calls >= 0),
    CONSTRAINT pipeline_runs_quota_check
        CHECK (quota_units_estimated >= 0),
    CONSTRAINT pipeline_runs_duration_check
        CHECK (duration_seconds IS NULL OR duration_seconds >= 0),
    CONSTRAINT pipeline_runs_time_check
        CHECK (finished_at IS NULL OR finished_at >= started_at),
    CONSTRAINT pipeline_runs_metadata_object_check
        CHECK (jsonb_typeof(metadata) = 'object')
);

CREATE TABLE IF NOT EXISTS pipeline_errors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_run_id BIGINT REFERENCES pipeline_runs(id) ON DELETE SET NULL,
    workflow TEXT NOT NULL,
    node TEXT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    error_type TEXT NOT NULL,
    error_message TEXT NOT NULL,
    external_id TEXT,
    retry_count INTEGER NOT NULL DEFAULT 0,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT pipeline_errors_retry_count_check
        CHECK (retry_count >= 0),
    CONSTRAINT pipeline_errors_metadata_object_check
        CHECK (jsonb_typeof(metadata) = 'object')
);

DROP TRIGGER IF EXISTS categories_set_updated_at ON categories;
CREATE TRIGGER categories_set_updated_at
BEFORE UPDATE ON categories
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS settings_set_updated_at ON settings;
CREATE TRIGGER settings_set_updated_at
BEFORE UPDATE ON settings
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS collection_queries_set_updated_at ON collection_queries;
CREATE TRIGGER collection_queries_set_updated_at
BEFORE UPDATE ON collection_queries
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS videos_set_updated_at ON videos;
CREATE TRIGGER videos_set_updated_at
BEFORE UPDATE ON videos
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMIT;
