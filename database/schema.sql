    CONSTRAINT video_classifications_content_type_check
        CHECK (content_type ~ '^[a-z0-9_]+$'),
    CONSTRAINT video_classifications_format_check
        CHECK (format ~ '^[a-z0-9_]+$'),
    CONSTRAINT video_classifications_hook_type_check
        CHECK (hook_type ~ '^[a-z0-9_]+$'),
    CONSTRAINT video_classifications_source_type_check
        CHECK (source_type ~ '^[a-z0-9_]+$'),
    CONSTRAINT video_classifications_presentation_style_check
        CHECK (presentation_style ~ '^[a-z0-9_]+$'),
    CONSTRAINT video_classifications_originality_check
        CHECK (originality_score BETWEEN 0 AND 1),
    CONSTRAINT video_classifications_copyright_risk_check
        CHECK (copyright_risk BETWEEN 0 AND 1),
    CONSTRAINT video_classifications_reused_risk_check
        CHECK (reused_content_risk BETWEEN 0 AND 1),
    CONSTRAINT video_classifications_confidence_check
        CHECK (ai_confidence BETWEEN 0 AND 1)
);

