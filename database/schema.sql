BEGIN;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT categories_slug_format_check
        CHECK (slug ~ '^[a-z0-9]+(?:_[a-z0-9]+)*$')
);

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value JSONB NOT NULL,
    description TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT settings_key_format_check
        CHECK (key ~ '^[A-Z][A-Z0-9_]*$')
);

CREATE TABLE IF NOT EXISTS collection_queries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    query_text TEXT NOT NULL,
    sample_group TEXT NOT NULL,
    language VARCHAR(16) NOT NULL DEFAULT 'pt',
    region CHAR(2) NOT NULL DEFAULT 'BR',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    priority SMALLINT NOT NULL DEFAULT 100,
    max_results_override INTEGER,
    last_collected_at TIMESTAMPTZ,
    last_status TEXT,
    consecutive_failures INTEGER NOT NULL DEFAULT 0,
    total_runs BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT collection_queries_query_text_check
        CHECK (length(btrim(query_text)) > 0),
    CONSTRAINT collection_queries_sample_group_check
        CHECK (sample_group IN ('recent', 'high_performance')),
    CONSTRAINT collection_queries_region_check
        CHECK (region = upper(region)),
    CONSTRAINT collection_queries_priority_check
        CHECK (priority >= 0),
    CONSTRAINT collection_queries_max_results_check
        CHECK (max_results_override IS NULL OR max_results_override > 0),
    CONSTRAINT collection_queries_last_status_check
        CHECK (last_status IS NULL OR last_status IN ('success', 'partial', 'failed', 'skipped')),
    CONSTRAINT collection_queries_consecutive_failures_check
        CHECK (consecutive_failures >= 0),
    CONSTRAINT collection_queries_total_runs_check
        CHECK (total_runs >= 0)
);

CREATE TABLE IF NOT EXISTS videos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform TEXT NOT NULL,
    external_id TEXT NOT NULL,
    channel_id TEXT NOT NULL,
    channel_name TEXT,
    title TEXT NOT NULL,
    description TEXT,
    url TEXT NOT NULL,
    published_at TIMESTAMPTZ NOT NULL,
    duration_seconds INTEGER,
    language VARCHAR(16),
    region CHAR(2),
    short_confidence TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT videos_platform_external_id_unique
        UNIQUE (platform, external_id),
    CONSTRAINT videos_platform_format_check
        CHECK (platform ~ '^[a-z0-9_]+$'),
    CONSTRAINT videos_external_id_check
        CHECK (length(btrim(external_id)) > 0),
    CONSTRAINT videos_duration_check
        CHECK (duration_seconds IS NULL OR duration_seconds >= 0),
    CONSTRAINT videos_region_check
        CHECK (region IS NULL OR region = upper(region)),
    CONSTRAINT videos_short_confidence_check
        CHECK (short_confidence IN ('high', 'medium', 'low'))
);

CREATE TABLE IF NOT EXISTS video_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id BIGINT NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
    collected_at TIMESTAMPTZ NOT NULL,
    views BIGINT NOT NULL,
    likes BIGINT,
    comments BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT video_snapshots_video_collected_unique
        UNIQUE (video_id, collected_at),
    CONSTRAINT video_snapshots_views_check
        CHECK (views >= 0),
    CONSTRAINT video_snapshots_likes_check
        CHECK (likes IS NULL OR likes >= 0),
    CONSTRAINT video_snapshots_comments_check
        CHECK (comments IS NULL OR comments >= 0)
);

CREATE TABLE IF NOT EXISTS video_classifications (
